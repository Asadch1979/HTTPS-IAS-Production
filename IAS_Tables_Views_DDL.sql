-- ============================================================================
-- T_AU_APPLICATION_AUDIT_LOG
-- Origin: 4ee365b2a262b69b90feef59d9ef7eff23c7ded9 (04 September 2026)
-- RESULT_STATUS includes FAILURE because the committed ApplicationAuditAttribute
-- writes that value when LogFailures is enabled. The source DDL omitted it.
-- ============================================================================

CREATE TABLE T_AU_APPLICATION_AUDIT_LOG
(
    ID                    NUMBER NOT NULL,
    EVENT_TIME            TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    EVENT_TYPE            VARCHAR2(50),
    ACTION_NAME           VARCHAR2(250) NOT NULL,
    ACTION_CATEGORY       VARCHAR2(100),
    MODULE_NAME           VARCHAR2(100),
    PPNO                  VARCHAR2(30),
    ROLE_ID               NUMBER,
    GROUP_ID              NUMBER,
    ENTITY_ID             NUMBER,
    USER_CONTEXT_ID       NUMBER,
    SESSION_ID            VARCHAR2(100),
    PAGE_ID               NUMBER,
    CONTROLLER_NAME       VARCHAR2(150),
    CONTROLLER_ACTION     VARCHAR2(150),
    API_PATH              VARCHAR2(500),
    HTTP_METHOD           VARCHAR2(20),
    DB_PACKAGE_NAME       VARCHAR2(100),
    DB_PROCEDURE_NAME     VARCHAR2(150),
    ENGAGEMENT_ID         NUMBER,
    PARA_ID               NUMBER,
    OLD_PARA_ID           NUMBER,
    NEW_PARA_ID           NUMBER,
    COM_ID                NUMBER,
    OBJECT_TYPE           VARCHAR2(100),
    OBJECT_ID             VARCHAR2(100),
    RESULT_STATUS         VARCHAR2(30) DEFAULT 'SUCCESS',
    RESULT_CODE           VARCHAR2(100),
    RESULT_MESSAGE        VARCHAR2(1000),
    CLIENT_IP_ADDRESS     VARCHAR2(100),
    PROXY_IP_ADDRESS      VARCHAR2(100),
    USER_AGENT            VARCHAR2(1000),
    TRACE_ID              VARCHAR2(150),
    REQUEST_ID            VARCHAR2(150),
    DURATION_MS           NUMBER,
    DETAILS               CLOB,
    CREATED_ON            TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_T_AU_APPLICATION_AUDIT_LOG PRIMARY KEY (ID),
    CONSTRAINT CK_APP_AUDIT_RESULT CHECK
        (RESULT_STATUS IN ('SUCCESS', 'FAILURE', 'VALIDATION', 'REJECTED', 'INFORMATION'))
);

CREATE SEQUENCE SEQ_T_AU_APPLICATION_AUDIT_LOG
    START WITH 1
    INCREMENT BY 1
    CACHE 100
    NOCYCLE;

CREATE INDEX IX_APP_AUDIT_EVENT_TIME
    ON T_AU_APPLICATION_AUDIT_LOG (EVENT_TIME);

CREATE INDEX IX_APP_AUDIT_PPNO
    ON T_AU_APPLICATION_AUDIT_LOG (PPNO, EVENT_TIME);

CREATE INDEX IX_APP_AUDIT_SESSION
    ON T_AU_APPLICATION_AUDIT_LOG (SESSION_ID);

CREATE INDEX IX_APP_AUDIT_ENTITY
    ON T_AU_APPLICATION_AUDIT_LOG (ENTITY_ID, EVENT_TIME);

CREATE INDEX IX_APP_AUDIT_ENGAGEMENT
    ON T_AU_APPLICATION_AUDIT_LOG (ENGAGEMENT_ID);

CREATE INDEX IX_APP_AUDIT_PARA
    ON T_AU_APPLICATION_AUDIT_LOG (PARA_ID);

CREATE INDEX IX_APP_AUDIT_COM
    ON T_AU_APPLICATION_AUDIT_LOG (COM_ID);

CREATE INDEX IX_APP_AUDIT_TRACE
    ON T_AU_APPLICATION_AUDIT_LOG (TRACE_ID);


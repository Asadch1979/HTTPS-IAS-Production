-- DATABASE-type IAS jobs are claimed and executed inside Oracle.
-- Application-type jobs continue to use the existing ASP.NET scheduler worker.
-- Only explicitly vetted procedure targets are accepted. No dynamic SQL.
CREATE OR REPLACE PACKAGE PKG_IAS_DB_JOB_WORKER AUTHID DEFINER IS
  PROCEDURE P_POLL;
END PKG_IAS_DB_JOB_WORKER;
/
CREATE OR REPLACE PACKAGE BODY PKG_IAS_DB_JOB_WORKER IS

  PROCEDURE P_REQUIRE_RECONCILIATION
  (
    P_EXECUTION_ID IN NUMBER,
    P_MESSAGE      IN VARCHAR2
  ) IS
    V_STATUS VARCHAR2(30);
  BEGIN
    -- Never overwrite a completion if P_COMPLETE_JOB already committed.
    SELECT E.STATUS INTO V_STATUS
      FROM T_IAS_JOB_EXECUTION E
      JOIN T_IAS_JOB_DEFINITION D ON D.JOB_ID = E.JOB_ID
     WHERE E.EXECUTION_ID = P_EXECUTION_ID
       AND D.EXECUTION_TYPE = 'DATABASE'
       FOR UPDATE OF E.STATUS;

    IF V_STATUS <> 'RUNNING' THEN
      COMMIT;
      RETURN;
    END IF;

    UPDATE T_IAS_JOB_EXECUTION
       SET STATUS = 'RECONCILIATION_REQUIRED',
           ERROR_MESSAGE = SUBSTR(P_MESSAGE, 1, 4000)
     WHERE EXECUTION_ID = P_EXECUTION_ID
       AND STATUS = 'RUNNING';

    UPDATE T_IAS_JOB_RUN_REQUEST R
       SET R.STATUS = 'RECONCILIATION_REQUIRED',
           R.UPDATED_BY = 'PKG_IAS_DB_JOB_WORKER',
           R.UPDATED_ON = SYSTIMESTAMP
     WHERE R.EXECUTION_ID = P_EXECUTION_ID
       AND R.STATUS = 'CLAIMED';

    UPDATE T_IAS_JOB_SCHEDULE S
       SET S.LAST_STATUS = 'RECONCILIATION_REQUIRED',
           S.LAST_ERROR = SUBSTR(P_MESSAGE, 1, 2000),
           S.UPDATED_BY = 'PKG_IAS_DB_JOB_WORKER',
           S.UPDATED_ON = SYSDATE
     WHERE EXISTS
       (SELECT 1 FROM T_IAS_JOB_EXECUTION E
         WHERE E.EXECUTION_ID = P_EXECUTION_ID
           AND E.SCHEDULE_ID = S.SCHEDULE_ID
           AND E.RUN_SOURCE = 'SCHEDULED');

    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;
  END P_REQUIRE_RECONCILIATION;

  PROCEDURE P_RUN_ONE
  (
    P_EXECUTION_ID IN NUMBER,
    P_EXECUTION_TYPE IN VARCHAR2,
    P_PACKAGE_NAME IN VARCHAR2,
    P_PROCEDURE_NAME IN VARCHAR2
  ) IS
    V_RESULT_CURSOR PKG_DAILY.T_CURSOR;
    V_ROWS          NUMBER;
    V_RUN_ID        NUMBER;
    V_STARTED       TIMESTAMP WITH TIME ZONE;
    V_COMPLETED     TIMESTAMP WITH TIME ZONE;
    V_STATUS        VARCHAR2(30);
    V_DB_STATUS     VARCHAR2(30);
    V_ERROR         VARCHAR2(4000);
    V_COMMITTED     BOOLEAN := FALSE;
  BEGIN
    -- Fixed allowlist: identifiers are NOT concatenated into executable SQL.
    IF P_EXECUTION_TYPE = 'DATABASE'
       AND UPPER(P_PACKAGE_NAME) = 'PKG_DAILY'
       AND UPPER(P_PROCEDURE_NAME) = 'SESSION_KILL_DAY_END' THEN

      PKG_DAILY.SESSION_KILL_DAY_END(
        IO_CURSOR => V_RESULT_CURSOR,
        P_EXECUTION_ID => P_EXECUTION_ID);

      FETCH V_RESULT_CURSOR
        INTO V_ROWS, V_RUN_ID, V_STARTED, V_COMPLETED, V_STATUS;

      IF V_RESULT_CURSOR%NOTFOUND THEN
        CLOSE V_RESULT_CURSOR;
        RAISE_APPLICATION_ERROR(-20820, 'Day-end procedure returned no result.');
      END IF;
      CLOSE V_RESULT_CURSOR;

      IF V_STATUS <> 'SUCCESS' OR V_ROWS IS NULL OR V_ROWS < 0 THEN
        RAISE_APPLICATION_ERROR(-20821, 'Unexpected day-end completion status.');
      END IF;

      V_COMMITTED := TRUE;
      PKG_IAS_SCHEDULER.P_COMPLETE_JOB(
        P_EXECUTION_ID => P_EXECUTION_ID,
        P_RECORDS_PROCESSED => V_ROWS,
        P_RESPONSE_MESSAGE =>
          SUBSTR('Oracle day-end run ' || V_RUN_ID ||
                 ': committed DML rows affected=' || V_ROWS, 1, 2000));
    ELSE
      PKG_IAS_SCHEDULER.P_FAIL_JOB(
        P_EXECUTION_ID,
        'Unapproved Oracle DATABASE job target: no matching allowlist entry.');
    END IF;

  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SUBSTR(SQLERRM || CHR(10) ||
                 DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 4000);
      IF V_RESULT_CURSOR%ISOPEN THEN
        CLOSE V_RESULT_CURSOR;
      END IF;

      -- If a commit may have succeeded, never mark a run as safely failed,
      -- as that could invite a harmful duplicate/retry.
      V_DB_STATUS := NULL;
      BEGIN
        SELECT STATUS INTO V_DB_STATUS
          FROM T_IAS_DAY_END_RUN
         WHERE IAS_EXECUTION_ID = P_EXECUTION_ID;
      EXCEPTION
        WHEN NO_DATA_FOUND THEN
          NULL;
      END;

      IF V_COMMITTED OR
         V_DB_STATUS IN ('SUCCESS', 'RUNNING', 'RECONCILIATION_REQUIRED') THEN
        P_REQUIRE_RECONCILIATION(
          P_EXECUTION_ID,
          'Oracle database job outcome requires review: ' || V_ERROR);
      ELSE
        -- PKG_DAILY rolled back the refresh if its internal status is FAILED.
        PKG_IAS_SCHEDULER.P_FAIL_JOB(P_EXECUTION_ID, V_ERROR);
      END IF;
  END P_RUN_ONE;

  PROCEDURE P_POLL IS
    V_CLAIM_CURSOR SYS_REFCURSOR;
    V_EXECUTION_ID NUMBER;
    V_SCHEDULE_ID  NUMBER;
    V_JOB_ID       NUMBER;
    V_JOB_CODE     VARCHAR2(100);
    V_JOB_NAME     VARCHAR2(200);
    V_EXECUTION_TYPE VARCHAR2(20);
    V_PACKAGE_NAME VARCHAR2(128);
    V_PROCEDURE_NAME VARCHAR2(128);
    V_HANDLER      VARCHAR2(150);
    V_EMAIL        CHAR(1);
    V_EXECUTION_KEY VARCHAR2(200);
    V_SCHEDULED_FOR TIMESTAMP WITH TIME ZONE;
    V_PERIOD_FROM   DATE;
    V_PERIOD_TO     DATE;
    V_RETRY_NO      NUMBER;
    V_RUN_SOURCE    VARCHAR2(20);
    V_REQUEST_ID    NUMBER;
  BEGIN
    -- Bound work per polling cycle; next minute processes any remaining jobs.
    FOR I IN 1..30 LOOP
      PKG_IAS_SCHEDULER.P_CLAIM_DUE_JOB(
        IO_CURSOR => V_CLAIM_CURSOR,
        P_EXECUTION_TYPE => 'DATABASE');

      FETCH V_CLAIM_CURSOR INTO
        V_EXECUTION_ID, V_SCHEDULE_ID, V_JOB_ID,
        V_JOB_CODE, V_JOB_NAME, V_EXECUTION_TYPE, V_PACKAGE_NAME,
        V_PROCEDURE_NAME, V_HANDLER, V_EMAIL, V_EXECUTION_KEY,
        V_SCHEDULED_FOR, V_PERIOD_FROM, V_PERIOD_TO, V_RETRY_NO,
        V_RUN_SOURCE, V_REQUEST_ID;

      IF V_CLAIM_CURSOR%NOTFOUND THEN
        CLOSE V_CLAIM_CURSOR;
        EXIT;
      END IF;
      CLOSE V_CLAIM_CURSOR;

      P_RUN_ONE(V_EXECUTION_ID, V_EXECUTION_TYPE,
                V_PACKAGE_NAME, V_PROCEDURE_NAME);
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      IF V_CLAIM_CURSOR%ISOPEN THEN
        CLOSE V_CLAIM_CURSOR;
      END IF;
      RAISE;
  END P_POLL;
END PKG_IAS_DB_JOB_WORKER;
/

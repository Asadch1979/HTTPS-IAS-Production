  COM_ID NUMBER, PERIOD_START DATE, PERIOD_END DATE,
  OFFICE_GROUP_ID NUMBER, OFFICE_GROUP_NAME VARCHAR2(500),
  OFFICE_ID NUMBER, OFFICE_NAME VARCHAR2(500),
  GM_ID NUMBER, GM_NAME VARCHAR2(500),
  REGION_ID NUMBER, REGION_CODE VARCHAR2(100), REGION_NAME VARCHAR2(500),
  FUNCTION_ID NUMBER, FUNCTION_NAME VARCHAR2(500),
  OPENING_BALANCE NUMBER, PARAS_ADDED NUMBER, SETTLED_PARAS NUMBER,
  OUTSTANDING_PARAS NUMBER, LOW_RISK NUMBER, MEDIUM_RISK NUMBER,
  HIGH_RISK NUMBER, UNRATED_RISK NUMBER,
  SETTLED_AUDIT NUMBER, SETTLED_COMPLIANCE NUMBER, SETTLED_UNKNOWN NUMBER,
  REOPENING_EVENTS NUMBER, RESETTLEMENT_EVENTS NUMBER, INITIALLY_CLOSED_ADDITIONS NUMBER,
  RECONCILIATION_DIFFERENCE NUMBER, AUDITOR_ASSIGNMENT_MISMATCH NUMBER

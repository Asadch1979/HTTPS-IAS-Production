-- Canonical, evidenced history required by PKG_EXEC_REPORTS. These tables are EMPTY
-- after deployment. Never seed initial states from today's PARA_STATUS or invent dates.
-- See ExecutiveReports.md and exec_reports_history_candidates.sql before importing.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
CREATE TABLE T_EXEC_REPORT_CASE_HISTORY (
  COM_ID NUMBER PRIMARY KEY,
  CREATED_ON DATE NOT NULL,
  INITIAL_OPEN NUMBER(1) NOT NULL CHECK (INITIAL_OPEN IN (0,1)),
  INITIAL_RISK NUMBER CHECK (INITIAL_RISK IN (1,2,3)),
  AUDIT_FAMILY VARCHAR2(20) NOT NULL CHECK (AUDIT_FAMILY IN ('FIELD','MANAGEMENT')),
  HISTORY_COMPLETE_THROUGH DATE NOT NULL,
  SOURCE_OBJECT VARCHAR2(128) NOT NULL,
  SOURCE_KEY VARCHAR2(256) NOT NULL,
  VERIFIED_BY VARCHAR2(128) NOT NULL,
  VERIFIED_ON DATE NOT NULL,
  CONSTRAINT CK_EXEC_HISTORY_COVERAGE CHECK (HISTORY_COMPLETE_THROUGH >= CREATED_ON)
);
CREATE TABLE T_EXEC_REPORT_HISTORY_EVENT (
  EVENT_KEY VARCHAR2(256) PRIMARY KEY,
  COM_ID NUMBER NOT NULL REFERENCES T_EXEC_REPORT_CASE_HISTORY(COM_ID),
  EVENT_ON DATE NOT NULL,
  EVENT_ORDER NUMBER NOT NULL CHECK (EVENT_ORDER > 0 AND EVENT_ORDER = TRUNC(EVENT_ORDER)),
  BEFORE_OPEN NUMBER(1) NOT NULL CHECK (BEFORE_OPEN IN (0,1)),
  AFTER_OPEN NUMBER(1) NOT NULL CHECK (AFTER_OPEN IN (0,1)),
  AFTER_RISK NUMBER CHECK (AFTER_RISK IN (1,2,3)),
  SETTLEMENT_SOURCE VARCHAR2(20) CHECK (SETTLEMENT_SOURCE IN ('AUDIT','COMPLIANCE','UNKNOWN')),
  SOURCE_OBJECT VARCHAR2(128) NOT NULL,
  SOURCE_KEY VARCHAR2(256) NOT NULL,
  VERIFIED_BY VARCHAR2(128) NOT NULL,
  VERIFIED_ON DATE NOT NULL,
  CONSTRAINT UQ_EXEC_HISTORY_ORDER UNIQUE (COM_ID, EVENT_ON, EVENT_ORDER),
  CONSTRAINT CK_EXEC_EVENT_SOURCE CHECK (
    (BEFORE_OPEN = 1 AND AFTER_OPEN = 0 AND SETTLEMENT_SOURCE IS NOT NULL)
    OR ((BEFORE_OPEN <> 1 OR AFTER_OPEN <> 0) AND SETTLEMENT_SOURCE IS NULL))
);
-- Evidence import is an owner/DBA operation. Application gets SELECT via definer's
-- rights package only; it must not receive INSERT/UPDATE/DELETE on these objects.

-- READ ONLY. Run as the package/table owner and retain the spool output.
-- The repository does not contain UQ_OBS_GIST DDL. These are its actual columns.
SELECT C.OWNER, C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE,
       C.STATUS, C.VALIDATED, CC.POSITION, CC.COLUMN_NAME
  FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC
    ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
 WHERE C.CONSTRAINT_NAME = 'UQ_OBS_GIST'
 ORDER BY CC.POSITION;

-- Also review PK/unique keys on both tables and any ID-generating triggers.
SELECT C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE, C.STATUS,
       CC.POSITION, CC.COLUMN_NAME
  FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC
    ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
 WHERE C.TABLE_NAME IN ('T_AU_OBSERVATION_GIST', 'T_AU_OBSERVATION_FINAL_RECCOMENDATION')
   AND C.CONSTRAINT_TYPE IN ('P', 'U')
 ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME, CC.POSITION;
SELECT TABLE_NAME, TRIGGER_NAME, STATUS, TRIGGER_BODY FROM USER_TRIGGERS
 WHERE TABLE_NAME IN ('T_AU_OBSERVATION_GIST', 'T_AU_OBSERVATION_FINAL_RECCOMENDATION');
SELECT 'GIST' AS SOURCE, OBS_ID, COUNT(*) AS RECORD_COUNT
  FROM T_AU_OBSERVATION_GIST GROUP BY OBS_ID HAVING COUNT(*) > 1
UNION ALL
SELECT 'RECOMMENDATION', OBS_ID, COUNT(*)
  FROM T_AU_OBSERVATION_FINAL_RECCOMENDATION GROUP BY OBS_ID HAVING COUNT(*) > 1;
SELECT NAME, TYPE, REFERENCED_NAME FROM USER_DEPENDENCIES
 WHERE REFERENCED_NAME IN ('T_AU_OBSERVATION_GIST', 'T_AU_OBSERVATION_FINAL_RECCOMENDATION');
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'T_IAS_JOB_EXECUTION' AND COLUMN_NAME = 'CREATED_ON')
    OR (TABLE_NAME = 'T_AU_SYSTEM_ERROR_HISTORY' AND COLUMN_NAME IN
       ('TECHNICAL_DETAILS', 'PAGE_ID', 'ENG_ID', 'PARA_ID', 'COM_ID'));

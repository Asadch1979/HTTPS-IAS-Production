CREATE OR REPLACE PROCEDURE PKG_INQ.GET_IID_TASK_LIST(
    P_UNIT_ID   IN NUMBER,
    IO_CURSOR   OUT PKG_INQ.T_CURSOR
) IS
BEGIN
  OPEN IO_CURSOR FOR
    SELECT h.COMPLAINT_ID,
           h.COMPLAINT_NO,
           d.COMPLAINANT_NAME,
           NVL(h.UPDATED_ON, h.SUBMITTED_ON) AS ASSIGNED_ON,
           h.STATUS,
           h.ASSIGNED_UNIT_ID,
           (SELECT MAX(p.PLAN_ID)
              FROM T_AU_IID_INV_PLAN p
             WHERE p.COMPLAINT_ID = h.COMPLAINT_ID) AS PLAN_ID
      FROM T_AU_IID_COMPLAINT_HDR h
      LEFT JOIN T_AU_IID_COMPLAINT_IAID d
        ON d.COMPLAINT_ID = h.COMPLAINT_ID
     WHERE h.ACTIVE_FLAG = 'Y'
       AND NVL(h.ASSIGNED_UNIT_ID, -1) = P_UNIT_ID
     ORDER BY NVL(h.UPDATED_ON, h.SUBMITTED_ON) DESC, h.COMPLAINT_ID DESC;
END;

-- Repository source only. Does not grant access or activate pages.
CREATE TABLE T_IAS_LEGACY_PARA_CONTROL (
  CONTROL_ID NUMBER(1) PRIMARY KEY CHECK (CONTROL_ID=1),
  ENABLED CHAR(1) DEFAULT 'N' NOT NULL CHECK (ENABLED IN ('N','Y'))
);
INSERT INTO T_IAS_LEGACY_PARA_CONTROL(CONTROL_ID,ENABLED) VALUES (1,'N');

-- Policy, not an audit-year master. No dates are inferred or seeded.
CREATE TABLE T_IAS_LEGACY_RECOGNITION (
  AUDIT_YEAR NUMBER(4) PRIMARY KEY CHECK (AUDIT_YEAR BETWEEN 1900 AND 2025),
  RECOGNITION_ON DATE NOT NULL,
  APPROVED_BY NUMBER NOT NULL,
  APPROVED_ON DATE NOT NULL,
  RULE_DESCRIPTION VARCHAR2(2000 CHAR) NOT NULL
);
CREATE SEQUENCE SEQ_IAS_LEGACY_REQUEST;
CREATE SEQUENCE SEQ_IAS_LEGACY_HISTORY;
CREATE TABLE T_IAS_LEGACY_PARA_REQUEST (
  REQUEST_ID NUMBER PRIMARY KEY,
  VERSION_NO NUMBER DEFAULT 1 NOT NULL,
  ENTITY_ID NUMBER NOT NULL,
  ENTITY_TYPE_ID NUMBER NOT NULL,
  AUDITED_BY NUMBER NOT NULL,
  AUDIT_YEAR NUMBER(4) NOT NULL CHECK (AUDIT_YEAR BETWEEN 1900 AND 2025),
  NATURE_ID NUMBER NOT NULL,
  PARA_NO VARCHAR2(100 CHAR) NOT NULL,
  HEADING VARCHAR2(500 CHAR) NOT NULL,
  ANNEXURE_ID NUMBER NOT NULL,
  CATEGORY_ID NUMBER NOT NULL,
  SUBCHECKLIST_ID NUMBER NOT NULL,
  CHECKLIST_ID NUMBER NOT NULL,
  RISK_ID NUMBER NOT NULL,
  REFERENCE_ID NUMBER,
  AMOUNT_INVOLVED NUMBER(18,2) NOT NULL CHECK (AMOUNT_INVOLVED>=0),
  NO_OF_INSTANCES NUMBER(10) NOT NULL CHECK (NO_OF_INSTANCES>=0),
  OBSERVATION_HTML CLOB NOT NULL,
  PAYLOAD_JSON CLOB NOT NULL CHECK (PAYLOAD_JSON IS JSON),
  REQUESTED_BY NUMBER NOT NULL,
  REQUEST_CONTEXT_ID NUMBER NOT NULL,
  REQUESTED_ON TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  SUBMITTED_ON TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  STATUS VARCHAR2(12) DEFAULT 'PENDING' NOT NULL
    CHECK (STATUS IN ('PENDING','RETURNED','REJECTED','AUTHORIZED')),
  REMARKS VARCHAR2(2000 CHAR),
  DECIDED_BY NUMBER,
  DECIDED_ON TIMESTAMP,
  LEGACY_PARA_ID NUMBER,
  LEGACY_REF_P VARCHAR2(100 CHAR),
  COMPLIANCE_ID NUMBER,
  RECOGNITION_ON DATE,
  CONSTRAINT CK_IAS_LEGACY_POSTED CHECK
    ((STATUS='AUTHORIZED' AND LEGACY_PARA_ID IS NOT NULL AND LEGACY_REF_P IS NOT NULL AND COMPLIANCE_ID IS NOT NULL AND RECOGNITION_ON IS NOT NULL)
      OR (STATUS<>'AUTHORIZED' AND LEGACY_PARA_ID IS NULL AND LEGACY_REF_P IS NULL AND COMPLIANCE_ID IS NULL))
);
-- Returned requests reserve their key while the originator corrects them.
CREATE UNIQUE INDEX UX_IAS_LEGACY_REQUEST_KEY ON T_IAS_LEGACY_PARA_REQUEST (
 CASE WHEN STATUS<>'REJECTED' THEN ENTITY_ID END,
 CASE WHEN STATUS<>'REJECTED' THEN AUDIT_YEAR END,
 CASE WHEN STATUS<>'REJECTED' THEN NATURE_ID END,
 CASE WHEN STATUS<>'REJECTED' THEN UPPER(TRIM(PARA_NO)) END
);
CREATE INDEX IX_IAS_LEGACY_MAKER ON T_IAS_LEGACY_PARA_REQUEST(REQUESTED_BY,AUDITED_BY,REQUEST_ID);
CREATE INDEX IX_IAS_LEGACY_QUEUE ON T_IAS_LEGACY_PARA_REQUEST(AUDITED_BY,STATUS,REQUEST_ID);
CREATE TABLE T_IAS_LEGACY_PARA_HISTORY (
  HISTORY_ID NUMBER PRIMARY KEY,
  REQUEST_ID NUMBER NOT NULL REFERENCES T_IAS_LEGACY_PARA_REQUEST(REQUEST_ID),
  VERSION_NO NUMBER NOT NULL,
  ACTION VARCHAR2(12) NOT NULL,
  STATUS VARCHAR2(12) NOT NULL,
  RISK_ID NUMBER NOT NULL,
  LEGACY_PARA_ID NUMBER,
  COMPLIANCE_ID NUMBER,
  ACTOR_PPNO NUMBER NOT NULL,
  CONTEXT_ID NUMBER NOT NULL,
  ACTION_ON TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  REMARKS VARCHAR2(2000 CHAR),
  PAYLOAD_JSON CLOB NOT NULL CHECK (PAYLOAD_JSON IS JSON)
);
-- Permanent legacy extension: unsupported final-table attributes, selected
-- reference, role details and attachment bytes remain accessible by legacy ID/REF_P.
CREATE TABLE T_IAS_LEGACY_PARA_ATTRIBUTES (
  LEGACY_PARA_ID NUMBER PRIMARY KEY,
  REF_P VARCHAR2(100 CHAR) NOT NULL UNIQUE,
  REQUEST_ID NUMBER NOT NULL UNIQUE REFERENCES T_IAS_LEGACY_PARA_REQUEST(REQUEST_ID),
  REFERENCE_ID NUMBER,
  PAYLOAD_JSON CLOB NOT NULL CHECK (PAYLOAD_JSON IS JSON)
);

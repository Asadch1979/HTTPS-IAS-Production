WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

CREATE TABLE T_AU_PLAN_DISABLED (
    ID                  NUMBER(18) NOT NULL,
    PLAN_ID             NUMBER(18) NOT NULL,
    CRITERIA_ID         NUMBER,
    AUDITPERIODID       NUMBER NOT NULL,
    AUDITEDBY           NUMBER NOT NULL,
    ENTITY_ID           NUMBER NOT NULL,
    ENTITY_CODE         VARCHAR2(100),
    AUDITEE_RISK        NUMBER,
    AUDITEE_SIZE        NUMBER,
    NO_OF_DAYS          NUMBER,
    FR_ID               NUMBER,
    ENTITY_TYPEID       NUMBER,
    PLAN_STATUS         VARCHAR2(10),
    NATURE_ID           NUMBER,
    F_ID                NUMBER,
    REASON              VARCHAR2(4000 BYTE) NOT NULL,
    REQUESTED_BY        NUMBER NOT NULL,
    REQUESTED_ON        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS              VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    AUTHORIZED_BY       NUMBER,
    AUTHORIZED_ON       TIMESTAMP,
    CONSTRAINT PK_AU_PLAN_DISABLED PRIMARY KEY (ID),
    CONSTRAINT UQ_AU_PLAN_DISABLED_PLAN UNIQUE (PLAN_ID),
    CONSTRAINT CK_AU_PLAN_DISABLED_STATUS CHECK (STATUS IN ('PENDING','AUTHORIZED')),
    CONSTRAINT CK_AU_PLAN_DISABLED_AUTH CHECK (
        (STATUS='PENDING' AND AUTHORIZED_BY IS NULL AND AUTHORIZED_ON IS NULL) OR
        (STATUS='AUTHORIZED' AND AUTHORIZED_BY IS NOT NULL AND AUTHORIZED_ON IS NOT NULL
         AND AUTHORIZED_BY <> REQUESTED_BY)
    ),
    CONSTRAINT CK_AU_PLAN_DISABLED_REASON CHECK (LENGTH(TRIM(REASON)) >= 10)
);

CREATE SEQUENCE SEQ_AU_PLAN_DISABLED_ID START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE INDEX IX_AU_PLAN_DISABLED_QUEUE
    ON T_AU_PLAN_DISABLED (STATUS, AUDITEDBY, REQUESTED_ON);

COMMENT ON TABLE T_AU_PLAN_DISABLED IS
    'Permanent audit evidence for authorized deletion of audit plan rows. PLAN_ID deliberately has no FK: original plan is deleted on authorization.';

COMMIT;

CREATE OR REPLACE PACKAGE BODY PKG_EMAIL AS
    FUNCTION NORMALIZE_KEY(P_VALUE VARCHAR2) RETURN VARCHAR2 IS
    BEGIN
        RETURN UPPER(TRIM(P_VALUE));
    END;

    PROCEDURE ASSERT_FLAG(P_VALUE NUMBER) IS
    BEGIN
        IF NVL(P_VALUE, -1) NOT IN (0, 1) THEN
            RAISE_APPLICATION_ERROR(-20010, 'Flag must be 0 or 1.');
        END IF;
    END;

    PROCEDURE ASSERT_STATUS(P_STATUS VARCHAR2) IS
    BEGIN
        IF P_STATUS NOT IN ('PENDING','SENT_TO_SMTP','SEND_FAILED','SKIPPED','BOUNCED','DELIVERED') THEN
            RAISE_APPLICATION_ERROR(-20011, 'Invalid email status.');
        END IF;
    END;

    PROCEDURE UPSERT_EVENT(
        P_EVENT_ID IN OUT NUMBER, P_EVENT_KEY IN VARCHAR2, P_DISPLAY_NAME IN VARCHAR2,
        P_DESCRIPTION IN VARCHAR2, P_IS_ENABLED IN NUMBER, P_USER IN VARCHAR2) IS
        V_KEY VARCHAR2(100);
    BEGIN
        ASSERT_FLAG(P_IS_ENABLED);
        V_KEY := NORMALIZE_KEY(P_EVENT_KEY);
        IF V_KEY IS NULL OR NOT REGEXP_LIKE(V_KEY, '^[A-Z0-9_]+$') THEN
            RAISE_APPLICATION_ERROR(-20012, 'Invalid event key.');
        END IF;
        IF P_EVENT_ID IS NULL OR P_EVENT_ID = 0 THEN
            INSERT INTO EM_EMAIL_EVENT(EVENT_KEY, DISPLAY_NAME, DESCRIPTION, IS_ENABLED, CREATED_BY)
            VALUES(V_KEY, TRIM(P_DISPLAY_NAME), P_DESCRIPTION, P_IS_ENABLED, P_USER)
            RETURNING EVENT_ID INTO P_EVENT_ID;
        ELSE
            UPDATE EM_EMAIL_EVENT
               SET EVENT_KEY = V_KEY, DISPLAY_NAME = TRIM(P_DISPLAY_NAME), DESCRIPTION = P_DESCRIPTION,
                   IS_ENABLED = P_IS_ENABLED, UPDATED_ON_UTC = SYS_EXTRACT_UTC(SYSTIMESTAMP), UPDATED_BY = P_USER
             WHERE EVENT_ID = P_EVENT_ID;
            IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20013, 'Email event not found.'); END IF;
        END IF;
    END;

    PROCEDURE SET_EVENT_ENABLED(P_EVENT_ID IN NUMBER, P_IS_ENABLED IN NUMBER, P_USER IN VARCHAR2) IS
    BEGIN
        ASSERT_FLAG(P_IS_ENABLED);
        UPDATE EM_EMAIL_EVENT SET IS_ENABLED = P_IS_ENABLED,
            UPDATED_ON_UTC = SYS_EXTRACT_UTC(SYSTIMESTAMP), UPDATED_BY = P_USER
        WHERE EVENT_ID = P_EVENT_ID;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20013, 'Email event not found.'); END IF;
    END;

    PROCEDURE GET_EVENTS(P_EVENT_ID IN NUMBER, O_CUR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN O_CUR FOR
            SELECT E.EVENT_ID, E.EVENT_KEY, E.DISPLAY_NAME, E.DESCRIPTION, E.IS_ENABLED,
                   E.ACTIVE_TEMPLATE_ID, T.TEMPLATE_NAME AS ACTIVE_TEMPLATE_NAME
              FROM EM_EMAIL_EVENT E
              LEFT JOIN EM_EMAIL_TEMPLATE T ON T.TEMPLATE_ID = E.ACTIVE_TEMPLATE_ID
             WHERE P_EVENT_ID IS NULL OR E.EVENT_ID = P_EVENT_ID
             ORDER BY E.DISPLAY_NAME;
    END;

    PROCEDURE UPSERT_TEMPLATE(
        P_TEMPLATE_ID IN OUT NUMBER, P_EVENT_ID IN NUMBER, P_TEMPLATE_NAME IN VARCHAR2,
        P_CULTURE IN VARCHAR2, P_SUBJECT_TEMPLATE IN CLOB, P_BODY_HTML_TEMPLATE IN CLOB,
        P_IS_ACTIVE IN NUMBER, P_USER IN VARCHAR2) IS
        V_VERSION NUMBER;
    BEGIN
        ASSERT_FLAG(P_IS_ACTIVE);
        IF P_TEMPLATE_ID IS NULL OR P_TEMPLATE_ID = 0 THEN
            SELECT NVL(MAX(VERSION_NO), 0) + 1 INTO V_VERSION FROM EM_EMAIL_TEMPLATE
             WHERE EVENT_ID = P_EVENT_ID AND TEMPLATE_NAME = TRIM(P_TEMPLATE_NAME) AND CULTURE = NVL(TRIM(P_CULTURE), 'en');
            INSERT INTO EM_EMAIL_TEMPLATE(EVENT_ID, TEMPLATE_NAME, CULTURE, SUBJECT_TEMPLATE,
                BODY_HTML_TEMPLATE, VERSION_NO, IS_ACTIVE, CREATED_BY)
            VALUES(P_EVENT_ID, TRIM(P_TEMPLATE_NAME), NVL(TRIM(P_CULTURE), 'en'), P_SUBJECT_TEMPLATE,
                P_BODY_HTML_TEMPLATE, V_VERSION, P_IS_ACTIVE, P_USER)
            RETURNING TEMPLATE_ID INTO P_TEMPLATE_ID;
        ELSE
            UPDATE EM_EMAIL_TEMPLATE SET TEMPLATE_NAME = TRIM(P_TEMPLATE_NAME),
                CULTURE = NVL(TRIM(P_CULTURE), 'en'), SUBJECT_TEMPLATE = P_SUBJECT_TEMPLATE,
                BODY_HTML_TEMPLATE = P_BODY_HTML_TEMPLATE, IS_ACTIVE = P_IS_ACTIVE,
                UPDATED_ON_UTC = SYS_EXTRACT_UTC(SYSTIMESTAMP), UPDATED_BY = P_USER
            WHERE TEMPLATE_ID = P_TEMPLATE_ID AND EVENT_ID = P_EVENT_ID;
            IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20014, 'Email template not found.'); END IF;
        END IF;
    END;

    PROCEDURE SET_ACTIVE_TEMPLATE(P_EVENT_ID IN NUMBER, P_TEMPLATE_ID IN NUMBER, P_USER IN VARCHAR2) IS V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_COUNT FROM EM_EMAIL_TEMPLATE
         WHERE TEMPLATE_ID = P_TEMPLATE_ID AND EVENT_ID = P_EVENT_ID AND IS_ACTIVE = 1;
        IF V_COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20015, 'Active template does not belong to event.'); END IF;
        UPDATE EM_EMAIL_EVENT SET ACTIVE_TEMPLATE_ID = P_TEMPLATE_ID,
            UPDATED_ON_UTC = SYS_EXTRACT_UTC(SYSTIMESTAMP), UPDATED_BY = P_USER
        WHERE EVENT_ID = P_EVENT_ID;
    END;

    PROCEDURE GET_TEMPLATES(P_EVENT_ID IN NUMBER, P_TEMPLATE_ID IN NUMBER, O_CUR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN O_CUR FOR SELECT T.TEMPLATE_ID, T.EVENT_ID, T.TEMPLATE_NAME, T.CULTURE,
            T.SUBJECT_TEMPLATE, T.BODY_HTML_TEMPLATE, T.VERSION_NO, T.IS_ACTIVE, E.EVENT_KEY
        FROM EM_EMAIL_TEMPLATE T JOIN EM_EMAIL_EVENT E ON E.EVENT_ID = T.EVENT_ID
        WHERE (P_EVENT_ID IS NULL OR T.EVENT_ID = P_EVENT_ID)
          AND (P_TEMPLATE_ID IS NULL OR T.TEMPLATE_ID = P_TEMPLATE_ID)
        ORDER BY E.EVENT_KEY, T.TEMPLATE_NAME, T.VERSION_NO DESC;
    END;

    PROCEDURE UPSERT_RULE(
        P_RULE_ID IN OUT NUMBER, P_EVENT_ID IN NUMBER, P_TO_RECIPIENTS IN VARCHAR2,
        P_CC_RECIPIENTS IN VARCHAR2, P_BCC_RECIPIENTS IN VARCHAR2,
        P_IS_ACTIVE IN NUMBER, P_USER IN VARCHAR2) IS
    BEGIN
        ASSERT_FLAG(P_IS_ACTIVE);
        MERGE INTO EM_EMAIL_RECIPIENT_RULE T
        USING (SELECT P_EVENT_ID EVENT_ID FROM DUAL) S ON (T.EVENT_ID = S.EVENT_ID)
        WHEN MATCHED THEN UPDATE SET T.TO_RECIPIENTS=P_TO_RECIPIENTS, T.CC_RECIPIENTS=P_CC_RECIPIENTS,
            T.BCC_RECIPIENTS=P_BCC_RECIPIENTS, T.IS_ACTIVE=P_IS_ACTIVE,
            T.UPDATED_ON_UTC=SYS_EXTRACT_UTC(SYSTIMESTAMP), T.UPDATED_BY=P_USER
        WHEN NOT MATCHED THEN INSERT(EVENT_ID,TO_RECIPIENTS,CC_RECIPIENTS,BCC_RECIPIENTS,IS_ACTIVE,CREATED_BY)
            VALUES(P_EVENT_ID,P_TO_RECIPIENTS,P_CC_RECIPIENTS,P_BCC_RECIPIENTS,P_IS_ACTIVE,P_USER);
        SELECT RULE_ID INTO P_RULE_ID FROM EM_EMAIL_RECIPIENT_RULE WHERE EVENT_ID=P_EVENT_ID;
    END;

    PROCEDURE GET_RULES(P_EVENT_ID IN NUMBER, O_CUR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN O_CUR FOR SELECT R.RULE_ID,R.EVENT_ID,R.TO_RECIPIENTS,R.CC_RECIPIENTS,
            R.BCC_RECIPIENTS,R.IS_ACTIVE,E.EVENT_KEY
        FROM EM_EMAIL_RECIPIENT_RULE R JOIN EM_EMAIL_EVENT E ON E.EVENT_ID=R.EVENT_ID
        WHERE P_EVENT_ID IS NULL OR R.EVENT_ID=P_EVENT_ID ORDER BY E.EVENT_KEY;
    END;

    PROCEDURE UPSERT_PLACEHOLDER(
        P_PLACEHOLDER_ID IN OUT NUMBER, P_EVENT_ID IN NUMBER, P_TOKEN IN VARCHAR2,
        P_DISPLAY_NAME IN VARCHAR2, P_TEST_VALUE IN CLOB, P_IS_ACTIVE IN NUMBER, P_USER IN VARCHAR2) IS
    BEGIN
        ASSERT_FLAG(P_IS_ACTIVE);
        IF NOT REGEXP_LIKE(TRIM(P_TOKEN), '^\{[A-Za-z0-9_.]+\}$') THEN
            RAISE_APPLICATION_ERROR(-20016, 'Invalid placeholder token.');
        END IF;
        MERGE INTO EM_EMAIL_PLACEHOLDER T
        USING (SELECT P_EVENT_ID EVENT_ID, TRIM(P_TOKEN) TOKEN FROM DUAL) S
        ON (T.EVENT_ID=S.EVENT_ID AND T.TOKEN=S.TOKEN)
        WHEN MATCHED THEN UPDATE SET T.DISPLAY_NAME=TRIM(P_DISPLAY_NAME),T.TEST_VALUE=P_TEST_VALUE,
            T.IS_ACTIVE=P_IS_ACTIVE,T.UPDATED_ON_UTC=SYS_EXTRACT_UTC(SYSTIMESTAMP),T.UPDATED_BY=P_USER
        WHEN NOT MATCHED THEN INSERT(EVENT_ID,TOKEN,DISPLAY_NAME,TEST_VALUE,IS_ACTIVE,CREATED_BY)
            VALUES(P_EVENT_ID,TRIM(P_TOKEN),TRIM(P_DISPLAY_NAME),P_TEST_VALUE,P_IS_ACTIVE,P_USER);
        SELECT PLACEHOLDER_ID INTO P_PLACEHOLDER_ID FROM EM_EMAIL_PLACEHOLDER
         WHERE EVENT_ID=P_EVENT_ID AND TOKEN=TRIM(P_TOKEN);
    END;

    PROCEDURE GET_PLACEHOLDERS(P_EVENT_ID IN NUMBER, O_CUR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN O_CUR FOR SELECT P.PLACEHOLDER_ID,P.EVENT_ID,P.TOKEN,P.DISPLAY_NAME,
            P.TEST_VALUE,P.IS_ACTIVE,E.EVENT_KEY
        FROM EM_EMAIL_PLACEHOLDER P JOIN EM_EMAIL_EVENT E ON E.EVENT_ID=P.EVENT_ID
        WHERE P_EVENT_ID IS NULL OR P.EVENT_ID=P_EVENT_ID ORDER BY E.EVENT_KEY,P.TOKEN;
    END;

    PROCEDURE GET_ATTACHMENTS(P_EVENT_ID IN NUMBER, O_CUR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN O_CUR FOR SELECT ATTACHMENT_ID,EVENT_ID,ATTACHMENT_NAME,SOURCE_TYPE,
            SOURCE_REFERENCE,FILE_NAME_PATTERN,IS_ACTIVE
        FROM EM_EMAIL_ATTACHMENT_DEF WHERE P_EVENT_ID IS NULL OR EVENT_ID=P_EVENT_ID
        ORDER BY EVENT_ID,ATTACHMENT_NAME;
    END;

    PROCEDURE UPSERT_ATTACHMENT(
        P_ATTACHMENT_ID IN OUT NUMBER, P_EVENT_ID IN NUMBER, P_ATTACHMENT_NAME IN VARCHAR2,
        P_SOURCE_TYPE IN VARCHAR2, P_SOURCE_REFERENCE IN VARCHAR2,
        P_FILE_NAME_PATTERN IN VARCHAR2, P_IS_ACTIVE IN NUMBER, P_USER IN VARCHAR2) IS
    BEGIN
        ASSERT_FLAG(P_IS_ACTIVE);
        IF P_SOURCE_TYPE NOT IN ('NONE', 'STATIC', 'FUTURE_PROVIDER') THEN
            RAISE_APPLICATION_ERROR(-20018, 'Invalid attachment source type.');
        END IF;
        IF P_ATTACHMENT_ID IS NULL OR P_ATTACHMENT_ID=0 THEN
            INSERT INTO EM_EMAIL_ATTACHMENT_DEF(EVENT_ID,ATTACHMENT_NAME,SOURCE_TYPE,
                SOURCE_REFERENCE,FILE_NAME_PATTERN,IS_ACTIVE,CREATED_BY)
            VALUES(P_EVENT_ID,TRIM(P_ATTACHMENT_NAME),P_SOURCE_TYPE,P_SOURCE_REFERENCE,
                P_FILE_NAME_PATTERN,P_IS_ACTIVE,P_USER)
            RETURNING ATTACHMENT_ID INTO P_ATTACHMENT_ID;
        ELSE
            UPDATE EM_EMAIL_ATTACHMENT_DEF SET ATTACHMENT_NAME=TRIM(P_ATTACHMENT_NAME),
                SOURCE_TYPE=P_SOURCE_TYPE,SOURCE_REFERENCE=P_SOURCE_REFERENCE,
                FILE_NAME_PATTERN=P_FILE_NAME_PATTERN,IS_ACTIVE=P_IS_ACTIVE,
                UPDATED_ON_UTC=SYS_EXTRACT_UTC(SYSTIMESTAMP),UPDATED_BY=P_USER
            WHERE ATTACHMENT_ID=P_ATTACHMENT_ID AND EVENT_ID=P_EVENT_ID;
            IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20019,'Attachment definition not found.'); END IF;
        END IF;
    END;

    PROCEDURE CREATE_LOG(
        P_LOG_ID OUT NUMBER, P_EVENT_KEY IN VARCHAR2, P_TEMPLATE_ID IN NUMBER,
        P_TEMPLATE_VERSION IN NUMBER, P_SUBJECT_SENT IN CLOB, P_BODY_SENT IN CLOB,
        P_TO_RECIPIENTS IN VARCHAR2, P_CC_RECIPIENTS IN VARCHAR2, P_BCC_RECIPIENTS IN VARCHAR2,
        P_ATTACHMENT_METADATA IN CLOB, P_STATUS IN VARCHAR2, P_SMTP_RESPONSE IN VARCHAR2,
        P_ATTEMPT_NUMBER IN NUMBER, P_CALLING_COMPONENT IN VARCHAR2, P_INITIATED_BY IN VARCHAR2,
        P_CORRELATION_ID IN VARCHAR2, P_REFERENCE_ID IN VARCHAR2, P_FAILURE_DETAILS IN CLOB) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        ASSERT_STATUS(P_STATUS);
        INSERT INTO EM_EMAIL_LOG(EVENT_KEY,TEMPLATE_ID,TEMPLATE_VERSION,SUBJECT_SENT,BODY_SENT,
            TO_RECIPIENTS,CC_RECIPIENTS,BCC_RECIPIENTS,ATTACHMENT_METADATA,STATUS,SMTP_RESPONSE,
            ATTEMPT_NUMBER,CALLING_COMPONENT,INITIATED_BY,CORRELATION_ID,REFERENCE_ID,FAILURE_DETAILS)
        VALUES(NORMALIZE_KEY(P_EVENT_KEY),P_TEMPLATE_ID,P_TEMPLATE_VERSION,P_SUBJECT_SENT,P_BODY_SENT,
            P_TO_RECIPIENTS,P_CC_RECIPIENTS,P_BCC_RECIPIENTS,P_ATTACHMENT_METADATA,P_STATUS,P_SMTP_RESPONSE,
            NVL(P_ATTEMPT_NUMBER,1),P_CALLING_COMPONENT,P_INITIATED_BY,P_CORRELATION_ID,P_REFERENCE_ID,P_FAILURE_DETAILS)
        RETURNING LOG_ID INTO P_LOG_ID;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
    END;

    PROCEDURE COMPLETE_LOG(P_LOG_ID IN NUMBER, P_STATUS IN VARCHAR2, P_SMTP_RESPONSE IN VARCHAR2,
        P_FAILURE_DETAILS IN CLOB) IS PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        ASSERT_STATUS(P_STATUS);
        UPDATE EM_EMAIL_LOG SET STATUS=P_STATUS,SMTP_RESPONSE=P_SMTP_RESPONSE,
            FAILURE_DETAILS=P_FAILURE_DETAILS,
            SENT_TO_SMTP_ON_UTC=CASE WHEN P_STATUS='SENT_TO_SMTP' THEN SYS_EXTRACT_UTC(SYSTIMESTAMP) ELSE NULL END
        WHERE LOG_ID=P_LOG_ID;
        IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20017,'Email log not found.'); END IF;
        COMMIT;
    EXCEPTION WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
    END;

    PROCEDURE GET_LOGS(
        P_LOG_ID IN NUMBER, P_FROM_UTC IN TIMESTAMP WITH TIME ZONE, P_TO_UTC IN TIMESTAMP WITH TIME ZONE,
        P_EVENT_KEY IN VARCHAR2, P_STATUS IN VARCHAR2, P_RECIPIENT IN VARCHAR2,
        P_SUBJECT IN VARCHAR2, P_CORRELATION_ID IN VARCHAR2, O_CUR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN O_CUR FOR SELECT LOG_ID,EVENT_KEY,TEMPLATE_ID,TEMPLATE_VERSION,SUBJECT_SENT,BODY_SENT,
            TO_RECIPIENTS,CC_RECIPIENTS,BCC_RECIPIENTS,ATTACHMENT_METADATA,ATTEMPTED_ON_UTC,
            STATUS,SMTP_RESPONSE,ATTEMPT_NUMBER,CALLING_COMPONENT,INITIATED_BY,CORRELATION_ID,
            REFERENCE_ID,SENT_TO_SMTP_ON_UTC,FAILURE_DETAILS
        FROM EM_EMAIL_LOG
        WHERE (P_LOG_ID IS NULL OR LOG_ID=P_LOG_ID)
          AND (P_FROM_UTC IS NULL OR ATTEMPTED_ON_UTC>=P_FROM_UTC)
          AND (P_TO_UTC IS NULL OR ATTEMPTED_ON_UTC<P_TO_UTC)
          AND (P_EVENT_KEY IS NULL OR EVENT_KEY=NORMALIZE_KEY(P_EVENT_KEY))
          AND (P_STATUS IS NULL OR STATUS=P_STATUS)
          AND (P_RECIPIENT IS NULL OR INSTR(LOWER(NVL(TO_RECIPIENTS,'')||';'||NVL(CC_RECIPIENTS,'')||';'||NVL(BCC_RECIPIENTS,'')),LOWER(P_RECIPIENT))>0)
          AND (P_SUBJECT IS NULL OR INSTR(LOWER(SUBJECT_SENT),LOWER(P_SUBJECT))>0)
          AND (P_CORRELATION_ID IS NULL OR CORRELATION_ID=P_CORRELATION_ID OR REFERENCE_ID=P_CORRELATION_ID)
        ORDER BY ATTEMPTED_ON_UTC DESC,LOG_ID DESC;
    END;
END PKG_EMAIL;

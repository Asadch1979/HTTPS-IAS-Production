-- Standalone AIS Email Management Module.
-- These EM_* objects are isolated from all legacy AIS email tables and queues.
-- Run as the AIS application schema owner.

CREATE TABLE EM_EMAIL_EVENT
(
    EVENT_ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENT_KEY           VARCHAR2(100 CHAR) NOT NULL,
    DISPLAY_NAME        VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(500 CHAR),
    IS_ENABLED          NUMBER(1) DEFAULT 1 NOT NULL,
    ACTIVE_TEMPLATE_ID  NUMBER,
    CREATED_ON_UTC      TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CREATED_BY          VARCHAR2(100 CHAR),
    UPDATED_ON_UTC      TIMESTAMP WITH TIME ZONE,
    UPDATED_BY          VARCHAR2(100 CHAR),
    CONSTRAINT PK_EM_EMAIL_EVENT PRIMARY KEY (EVENT_ID),
    CONSTRAINT UQ_EM_EMAIL_EVENT_KEY UNIQUE (EVENT_KEY),
    CONSTRAINT CK_EM_EMAIL_EVENT_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CK_EM_EMAIL_EVENT_KEY CHECK (EVENT_KEY = UPPER(TRIM(EVENT_KEY)))
);

CREATE TABLE EM_EMAIL_TEMPLATE
(
    TEMPLATE_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENT_ID            NUMBER NOT NULL,
    TEMPLATE_NAME       VARCHAR2(150 CHAR) NOT NULL,
    CULTURE             VARCHAR2(10 CHAR) DEFAULT 'en' NOT NULL,
    SUBJECT_TEMPLATE    CLOB NOT NULL,
    BODY_HTML_TEMPLATE  CLOB NOT NULL,
    VERSION_NO          NUMBER(10) DEFAULT 1 NOT NULL,
    IS_ACTIVE           NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_ON_UTC      TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CREATED_BY          VARCHAR2(100 CHAR),
    UPDATED_ON_UTC      TIMESTAMP WITH TIME ZONE,
    UPDATED_BY          VARCHAR2(100 CHAR),
    CONSTRAINT PK_EM_EMAIL_TEMPLATE PRIMARY KEY (TEMPLATE_ID),
    CONSTRAINT FK_EM_TEMPLATE_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EM_EMAIL_EVENT(EVENT_ID),
    CONSTRAINT UQ_EM_TEMPLATE_VERSION UNIQUE (EVENT_ID, TEMPLATE_NAME, CULTURE, VERSION_NO),
    CONSTRAINT CK_EM_TEMPLATE_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_EM_TEMPLATE_VERSION CHECK (VERSION_NO > 0)
);

ALTER TABLE EM_EMAIL_EVENT ADD CONSTRAINT FK_EM_EVENT_ACTIVE_TEMPLATE
    FOREIGN KEY (ACTIVE_TEMPLATE_ID) REFERENCES EM_EMAIL_TEMPLATE(TEMPLATE_ID);

CREATE TABLE EM_EMAIL_RECIPIENT_RULE
(
    RULE_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENT_ID        NUMBER NOT NULL,
    TO_RECIPIENTS   VARCHAR2(2000 CHAR),
    CC_RECIPIENTS   VARCHAR2(2000 CHAR),
    BCC_RECIPIENTS  VARCHAR2(2000 CHAR),
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_ON_UTC  TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR),
    UPDATED_ON_UTC  TIMESTAMP WITH TIME ZONE,
    UPDATED_BY      VARCHAR2(100 CHAR),
    CONSTRAINT PK_EM_EMAIL_RECIPIENT_RULE PRIMARY KEY (RULE_ID),
    CONSTRAINT FK_EM_RULE_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EM_EMAIL_EVENT(EVENT_ID),
    CONSTRAINT UQ_EM_RULE_EVENT UNIQUE (EVENT_ID),
    CONSTRAINT CK_EM_RULE_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE EM_EMAIL_PLACEHOLDER
(
    PLACEHOLDER_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENT_ID        NUMBER NOT NULL,
    TOKEN           VARCHAR2(100 CHAR) NOT NULL,
    DISPLAY_NAME    VARCHAR2(100 CHAR) NOT NULL,
    TEST_VALUE      CLOB,
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_ON_UTC  TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CREATED_BY      VARCHAR2(100 CHAR),
    UPDATED_ON_UTC  TIMESTAMP WITH TIME ZONE,
    UPDATED_BY      VARCHAR2(100 CHAR),
    CONSTRAINT PK_EM_EMAIL_PLACEHOLDER PRIMARY KEY (PLACEHOLDER_ID),
    CONSTRAINT FK_EM_PLACEHOLDER_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EM_EMAIL_EVENT(EVENT_ID),
    CONSTRAINT UQ_EM_PLACEHOLDER_TOKEN UNIQUE (EVENT_ID, TOKEN),
    CONSTRAINT CK_EM_PLACEHOLDER_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_EM_PLACEHOLDER_TOKEN CHECK (TOKEN LIKE '{%}')
);

CREATE TABLE EM_EMAIL_ATTACHMENT_DEF
(
    ATTACHMENT_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENT_ID            NUMBER NOT NULL,
    ATTACHMENT_NAME     VARCHAR2(150 CHAR) NOT NULL,
    SOURCE_TYPE         VARCHAR2(30 CHAR) NOT NULL,
    SOURCE_REFERENCE    VARCHAR2(500 CHAR) NOT NULL,
    FILE_NAME_PATTERN   VARCHAR2(250 CHAR),
    IS_ACTIVE           NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_ON_UTC      TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CREATED_BY          VARCHAR2(100 CHAR),
    UPDATED_ON_UTC      TIMESTAMP WITH TIME ZONE,
    UPDATED_BY          VARCHAR2(100 CHAR),
    CONSTRAINT PK_EM_EMAIL_ATTACHMENT_DEF PRIMARY KEY (ATTACHMENT_ID),
    CONSTRAINT FK_EM_ATTACHMENT_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EM_EMAIL_EVENT(EVENT_ID),
    CONSTRAINT UQ_EM_ATTACHMENT_NAME UNIQUE (EVENT_ID, ATTACHMENT_NAME),
    CONSTRAINT CK_EM_ATTACHMENT_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_EM_ATTACHMENT_SOURCE CHECK (SOURCE_TYPE IN ('NONE', 'STATIC', 'FUTURE_PROVIDER'))
);

CREATE TABLE EM_EMAIL_LOG
(
    LOG_ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENT_KEY               VARCHAR2(100 CHAR) NOT NULL,
    TEMPLATE_ID             NUMBER,
    TEMPLATE_VERSION        NUMBER(10),
    SUBJECT_SENT            CLOB,
    BODY_SENT               CLOB,
    TO_RECIPIENTS           VARCHAR2(2000 CHAR),
    CC_RECIPIENTS           VARCHAR2(2000 CHAR),
    BCC_RECIPIENTS          VARCHAR2(2000 CHAR),
    ATTACHMENT_METADATA     CLOB,
    ATTEMPTED_ON_UTC        TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    STATUS                  VARCHAR2(30 CHAR) NOT NULL,
    SMTP_RESPONSE           VARCHAR2(2000 CHAR),
    ATTEMPT_NUMBER          NUMBER(10) DEFAULT 1 NOT NULL,
    CALLING_COMPONENT       VARCHAR2(200 CHAR),
    INITIATED_BY            VARCHAR2(100 CHAR),
    CORRELATION_ID          VARCHAR2(100 CHAR) NOT NULL,
    REFERENCE_ID            VARCHAR2(200 CHAR),
    SENT_TO_SMTP_ON_UTC     TIMESTAMP WITH TIME ZONE,
    FAILURE_DETAILS         CLOB,
    CONSTRAINT PK_EM_EMAIL_LOG PRIMARY KEY (LOG_ID),
    CONSTRAINT FK_EM_LOG_TEMPLATE FOREIGN KEY (TEMPLATE_ID) REFERENCES EM_EMAIL_TEMPLATE(TEMPLATE_ID),
    CONSTRAINT CK_EM_EMAIL_LOG_STATUS CHECK
        (STATUS IN ('PENDING','SENT_TO_SMTP','SEND_FAILED','SKIPPED','BOUNCED','DELIVERED')),
    CONSTRAINT CK_EM_EMAIL_LOG_ATTEMPT CHECK (ATTEMPT_NUMBER > 0)
);

CREATE INDEX IX_EM_TEMPLATE_EVENT ON EM_EMAIL_TEMPLATE(EVENT_ID, IS_ACTIVE);

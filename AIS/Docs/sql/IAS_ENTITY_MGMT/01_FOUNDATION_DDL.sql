-- IAS ENTITY MANAGEMENT | PHASE 1 | FOUNDATION DDL
-- REQUIRED: run 00_PREFLIGHT.sql and review all results FIRST.
-- Execute only in an approved staging environment and from the schema owning
-- AIS_T_AU_POST_COMPLIANCE. Oracle DDL auto-commits and is NOT transactionally rolled back.
-- Does not change T_AUDITEE_ENTITIES, T_AUDITEE_ENTITIES_MAPING or any para data.
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT Starting IAS Entity Management foundation DDL
DECLARE
  v_count NUMBER;
BEGIN
  FOR t IN (SELECT 'T_AUDITEE_ENTITIES' table_name FROM dual
            UNION ALL SELECT 'T_AUDITEE_ENTITIES_MAPING' FROM dual
            UNION ALL SELECT 'AIS_T_AU_POST_COMPLIANCE' FROM dual) LOOP
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name=t.table_name;
    IF v_count<>1 THEN
      RAISE_APPLICATION_ERROR(-20701,'Required owner table missing: '||t.table_name);
    END IF;
  END LOOP;
  SELECT COUNT(*) INTO v_count FROM user_objects
   WHERE object_name IN ('T_IAS_ENTITY_CHANGE_LOG','T_IAS_ENTITY_PARA_ARCHIVE',
                         'S_IAS_ENTITY_CHANGE_LOG','S_IAS_ENTITY_PARA_ARCHIVE',
                         'IX_IAS_ENTITY_LOG_ENTITY_ON','IX_IAS_ENTITY_LOG_BATCH',
                         'IX_IAS_ENTITY_LOG_REQUEST','IX_IAS_ENTITY_ARCHIVE_ENT_COM',
                         'IX_IAS_ENTITY_ARCHIVE_DATE','TR_IAS_ENT_LOG_IMMUT',
                         'TR_IAS_ENT_ARC_IMMUT');
  IF v_count>0 THEN
    RAISE_APPLICATION_ERROR(-20702,'A Foundation object already exists; stop and reconcile. Do not rerun blindly.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM user_tab_columns
   WHERE table_name='AIS_T_AU_POST_COMPLIANCE'
     AND column_name IN ('COM_ID','ENTITY_ID','PARA_STATUS','PARA_ADDED_ON','SETTELED_ON');
  IF v_count<>5 THEN
    RAISE_APPLICATION_ERROR(-20703,'Post-compliance source columns differ from required contract.');
  END IF;
END;
/

-- A change event is append-only. Use one row per entity and state transition;
-- group bulk operations via BATCH_ID / CORRELATION_ID.
CREATE TABLE T_IAS_ENTITY_CHANGE_LOG
(
  LOG_ID             NUMBER(19) NOT NULL,
  REQUEST_ID         NUMBER(19),
  BATCH_ID           NUMBER(19),
  ENTITY_ID          NUMBER(38) NOT NULL,
  TARGET_ENTITY_ID   NUMBER(38),
  ACTION_CODE        VARCHAR2(40) NOT NULL,
  EVENT_STATUS       VARCHAR2(25) NOT NULL,
  OLD_VALUES         CLOB,
  NEW_VALUES         CLOB,
  CHANGE_REASON      VARCHAR2(2000),
  REFERENCE_NO       VARCHAR2(200),
  EFFECTIVE_ON       DATE,
  ACTOR_PPNO         VARCHAR2(60),
  ACTOR_ROLE_ID      NUMBER,
  ACTOR_ENTITY_ID    NUMBER(38),
  AUTHORIZED_BY      VARCHAR2(60),
  AUTHORIZED_ON      TIMESTAMP(6),
  EXECUTED_BY        VARCHAR2(60),
  EXECUTED_ON        TIMESTAMP(6),
  RECORDED_ON        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  SOURCE_MODULE      VARCHAR2(100),
  CORRELATION_ID     VARCHAR2(100),
  RESULT_MESSAGE     VARCHAR2(4000),
  CONSTRAINT PK_IAS_ENTITY_CHANGE_LOG PRIMARY KEY (LOG_ID),
  CONSTRAINT CK_IAS_ENTITY_LOG_STATUS CHECK (EVENT_STATUS IN
    ('REQUESTED','APPROVED','REJECTED','COMPLETED','FAILED','CANCELLED','PREVIEW'))
) TABLESPACE MISC;

CREATE SEQUENCE S_IAS_ENTITY_CHANGE_LOG START WITH 1 INCREMENT BY 1 CACHE 50 NOCYCLE;
CREATE INDEX IX_IAS_ENTITY_LOG_ENTITY_ON ON T_IAS_ENTITY_CHANGE_LOG (ENTITY_ID, RECORDED_ON);
CREATE INDEX IX_IAS_ENTITY_LOG_BATCH ON T_IAS_ENTITY_CHANGE_LOG (BATCH_ID, LOG_ID);
CREATE INDEX IX_IAS_ENTITY_LOG_REQUEST ON T_IAS_ENTITY_CHANGE_LOG (REQUEST_ID, LOG_ID);

-- Capture EVERY currently existing source field, including fields absent from
-- old repository documents. This is a source-schema snapshot, NOT a migration.
-- Archive metadata columns precede a P.* clone. No rows copied yet.
CREATE TABLE T_IAS_ENTITY_PARA_ARCHIVE TABLESPACE MISC AS
SELECT CAST(NULL AS NUMBER(19)) AS ARCHIVE_ID,
       CAST(NULL AS NUMBER(19)) AS ENTITY_LOG_ID,
       CAST(NULL AS TIMESTAMP(6)) AS ARCHIVED_ON,
       CAST(NULL AS VARCHAR2(60)) AS ARCHIVED_BY,
       CAST(NULL AS VARCHAR2(2000)) AS CLOSURE_REASON,
       p.*
  FROM AIS_T_AU_POST_COMPLIANCE p
 WHERE 1=0;

ALTER TABLE T_IAS_ENTITY_PARA_ARCHIVE MODIFY (ARCHIVE_ID NOT NULL, ENTITY_LOG_ID NOT NULL, ARCHIVED_ON NOT NULL);
ALTER TABLE T_IAS_ENTITY_PARA_ARCHIVE ADD CONSTRAINT PK_IAS_ENTITY_PARA_ARCHIVE PRIMARY KEY (ARCHIVE_ID);
ALTER TABLE T_IAS_ENTITY_PARA_ARCHIVE ADD CONSTRAINT FK_IAS_ENTITY_PARA_LOG
  FOREIGN KEY (ENTITY_LOG_ID) REFERENCES T_IAS_ENTITY_CHANGE_LOG (LOG_ID);
ALTER TABLE T_IAS_ENTITY_PARA_ARCHIVE ADD CONSTRAINT UQ_IAS_ENTITY_PARA_EVENT UNIQUE (ENTITY_LOG_ID, COM_ID);
CREATE SEQUENCE S_IAS_ENTITY_PARA_ARCHIVE START WITH 1 INCREMENT BY 1 CACHE 50 NOCYCLE;
CREATE INDEX IX_IAS_ENTITY_ARCHIVE_ENT_COM ON T_IAS_ENTITY_PARA_ARCHIVE (ENTITY_ID, COM_ID);
CREATE INDEX IX_IAS_ENTITY_ARCHIVE_DATE ON T_IAS_ENTITY_PARA_ARCHIVE (ARCHIVED_ON);

-- Prevent silent alteration of completed business history. A restoration is a
-- NEW event, not a modification of a historic record. No autonomous commit.
CREATE OR REPLACE TRIGGER TR_IAS_ENT_LOG_IMMUT
BEFORE UPDATE OR DELETE ON T_IAS_ENTITY_CHANGE_LOG
BEGIN
  RAISE_APPLICATION_ERROR(-20720,'IAS entity change log is append-only.');
END;
/
CREATE OR REPLACE TRIGGER TR_IAS_ENT_ARC_IMMUT
BEFORE UPDATE OR DELETE ON T_IAS_ENTITY_PARA_ARCHIVE
BEGIN
  RAISE_APPLICATION_ERROR(-20721,'IAS entity para archive is immutable.');
END;
/


CREATE OR REPLACE TRIGGER TR_FR_PROCESS_LOCK
BEFORE INSERT OR UPDATE OR DELETE ON T_FAD_RISK_PROCESS FOR EACH ROW
DECLARE s VARCHAR2(15); k NUMBER;
BEGIN
 IF UPDATING AND :OLD.version_id<>:NEW.version_id THEN RAISE_APPLICATION_ERROR(-20045,'Parent cannot change.'); END IF;
 IF DELETING THEN k:=:OLD.version_id; ELSE k:=:NEW.version_id; END IF;
 SELECT state INTO s FROM T_FAD_RISK_VERSION WHERE version_id=k FOR UPDATE;
 IF s='PUBLISHED' THEN RAISE_APPLICATION_ERROR(-20045,'Immutable parent.'); END IF;
END;
/

-- Additive, source only. Oracle 19c+. No grants or IAS data mutations.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE T_FAD_ENGINE_POLICY (
 policy_id NUMBER PRIMARY KEY, approval_ref VARCHAR2(500) NOT NULL,
 entity_type_id NUMBER NOT NULL, engagement_status NUMBER NOT NULL,
 observation_status NUMBER NOT NULL,
 UNIQUE(entity_type_id,engagement_status,observation_status));
-- Empty until approved final statuses and branch type are established.
CREATE TABLE T_FAD_RISK_ENGINE_RUN (
 run_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 period_id NUMBER NOT NULL, entity_type_id NUMBER, entity_id NUMBER,
 audit_office_id NUMBER NOT NULL, actor_id NUMBER NOT NULL,
 started_on TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, completed_on TIMESTAMP,
 engine_version VARCHAR2(40) DEFAULT 'FAD-ENGINE-1' NOT NULL,
 status VARCHAR2(30) NOT NULL, processed NUMBER DEFAULT 0 NOT NULL,
 skipped NUMBER DEFAULT 0 NOT NULL, pending NUMBER DEFAULT 0 NOT NULL, failed NUMBER DEFAULT 0 NOT NULL);
CREATE TABLE T_FAD_RISK_ENGINE_RESULT (
 result_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 run_id NUMBER NOT NULL REFERENCES T_FAD_RISK_ENGINE_RUN,
 eng_id NUMBER NOT NULL, entity_id NUMBER NOT NULL, entity_name VARCHAR2(500),
 entity_type_id NUMBER NOT NULL, version_id NUMBER,
 source_sha256 VARCHAR2(64), policy_snapshot CLOB,
 observations NUMBER, instances NUMBER, score NUMBER, risk_rating VARCHAR2(30),
 status VARCHAR2(30) NOT NULL, calculated_on TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 UNIQUE(run_id,eng_id));
CREATE TABLE T_FAD_RISK_ENGINE_DETAIL (
 detail_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 result_id NUMBER NOT NULL REFERENCES T_FAD_RISK_ENGINE_RESULT,
 node_level VARCHAR2(20) NOT NULL, main_code VARCHAR2(200), package_code VARCHAR2(200),
 process_code VARCHAR2(200), procedure_code VARCHAR2(200), source_row NUMBER,
 annex_id NUMBER, source_code VARCHAR2(100), description CLOB, risk_classification VARCHAR2(100),
 observation_id NUMBER, reference_id VARCHAR2(200), observations NUMBER, instances NUMBER,
 score NUMBER, status VARCHAR2(30) NOT NULL);
CREATE TABLE T_FAD_RISK_ENGINE_EXCEPTION (
 exception_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 result_id NUMBER NOT NULL REFERENCES T_FAD_RISK_ENGINE_RESULT,
 code VARCHAR2(50) NOT NULL, message VARCHAR2(2000) NOT NULL, technical_details CLOB);
CREATE TABLE T_FAD_ENGINE_LOCK (eng_id NUMBER PRIMARY KEY);
CREATE OR REPLACE VIEW V_FAD_RISK_ENGINE_RESULTS AS
 SELECT r.*,u.period_id,u.audit_office_id,u.actor_id,u.engine_version
 FROM T_FAD_RISK_ENGINE_RESULT r JOIN T_FAD_RISK_ENGINE_RUN u ON u.run_id=r.run_id
 WITH READ ONLY;

CREATE OR REPLACE TRIGGER TR_FRE_RESULT_HISTORY
 BEFORE UPDATE OR DELETE ON T_FAD_RISK_ENGINE_RESULT FOR EACH ROW
 DECLARE n NUMBER;
 BEGIN
 SELECT COUNT(*) INTO n FROM T_FAD_RISK_ENGINE_RUN u
 WHERE u.run_id=:OLD.run_id AND u.completed_on IS NOT NULL;
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20044,'Completed engine history is immutable'); END IF;
 END;
/

CREATE OR REPLACE TRIGGER TR_FRE_DETAIL_HISTORY
 BEFORE UPDATE OR DELETE ON T_FAD_RISK_ENGINE_DETAIL FOR EACH ROW
 DECLARE n NUMBER;
 BEGIN
 SELECT COUNT(*) INTO n FROM T_FAD_RISK_ENGINE_RUN u JOIN T_FAD_RISK_ENGINE_RESULT r ON r.run_id=u.run_id
 WHERE r.result_id=:OLD.result_id AND u.completed_on IS NOT NULL;
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20044,'Completed engine history is immutable'); END IF;
 END;
/

CREATE OR REPLACE TRIGGER TR_FRE_EXCEPTION_HISTORY
 BEFORE UPDATE OR DELETE ON T_FAD_RISK_ENGINE_EXCEPTION FOR EACH ROW
 DECLARE n NUMBER;
 BEGIN
 SELECT COUNT(*) INTO n FROM T_FAD_RISK_ENGINE_RUN u JOIN T_FAD_RISK_ENGINE_RESULT r ON r.run_id=u.run_id
 WHERE r.result_id=:OLD.result_id AND u.completed_on IS NOT NULL;
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20044,'Completed engine history is immutable'); END IF;
 END;
/

CREATE OR REPLACE TRIGGER TR_FRE_RUN_HISTORY
 BEFORE UPDATE OR DELETE ON T_FAD_RISK_ENGINE_RUN FOR EACH ROW
 BEGIN
 IF :OLD.completed_on IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20044,'Completed run is immutable'); END IF;
 END;
/

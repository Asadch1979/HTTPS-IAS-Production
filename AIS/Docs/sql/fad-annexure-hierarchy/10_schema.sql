-- DDL ONLY, one-time extension. Oracle DDL implicitly commits.
-- Review live schema first. Target: checked-in Table_Structure_for_Codex.txt.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM user_constraints c
 WHERE c.table_name='T_AUDIT_CHECKLIST_ANNEXURE' AND c.constraint_type IN ('P','U')
 AND c.status='ENABLED' AND c.validated='VALIDATED'
 AND (SELECT COUNT(*) FROM user_cons_columns x WHERE x.constraint_name=c.constraint_name)=1
 AND EXISTS (SELECT 1 FROM user_cons_columns x WHERE x.constraint_name=c.constraint_name AND x.column_name='ID');
 IF n=0 THEN RAISE_APPLICATION_ERROR(-20100,'IAS Annexure ID needs an existing validated unique key; stop for schema owner review. Do not alter Annexure master.'); END IF;
 SELECT COUNT(*) INTO n FROM user_tables WHERE table_name='T_RISK_FAD_PACKAGE';
 IF n=0 THEN
 EXECUTE IMMEDIATE 'CREATE TABLE T_RISK_FAD_PACKAGE (
 PACKAGE_ID NUMBER CONSTRAINT PK_FAD_PACKAGE PRIMARY KEY,
 CONSTRAINT FK_FAD_PACKAGE_SUB FOREIGN KEY (PACKAGE_ID) REFERENCES T_RISK_FAD_KPI_SUB(KPI_SUB_ID))';
 END IF;
END;
/

ALTER TABLE T_RISK_FAD_KPI_SUB MODIFY (KPI_SUB_NAME VARCHAR2(4000 BYTE));
ALTER TABLE T_RISK_FAD_PROCESS MODIFY (PROCESS_NAME VARCHAR2(4000 BYTE));
ALTER TABLE T_RISK_FAD_SUB_PROCESS MODIFY (SUB_PROCESS_NAME VARCHAR2(4000 BYTE));
ALTER TABLE T_RISK_FAD_PROCESS ADD (PACKAGE_ID NUMBER);
ALTER TABLE T_RISK_FAD_PROCESS ADD CONSTRAINT FK_FAD_PROCESS_PACKAGE FOREIGN KEY (PACKAGE_ID) REFERENCES T_RISK_FAD_PACKAGE(PACKAGE_ID);
ALTER TABLE T_RISK_FAD_PROCESS ADD CONSTRAINT CK_FAD_PROCESS_PACKAGE CHECK (PACKAGE_ID IS NULL OR PACKAGE_ID=KPI_SUB_ID);
CREATE INDEX IX_FAD_PROCESS_PACKAGE ON T_RISK_FAD_PROCESS(PACKAGE_ID);

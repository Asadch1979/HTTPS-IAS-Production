/*
  IID Exceptions Module
  Production-style executable script aligned with DBConnection.IID.ExceptionReports.cs

  Design notes:
  - Keeps ONE package only: PKG_ISM.
  - Exposes exactly the procedure names used by DBConnection.IID.ExceptionReports.cs.
  - Avoids hard compile-time dependency on unknown legacy objects by using metadata-driven dynamic SQL.
  - Supports reruns through safe drop blocks.
  - Includes header/format/entity/role/source metadata, history, and execution log.
  - Returns column names expected by the existing C# models.
*/


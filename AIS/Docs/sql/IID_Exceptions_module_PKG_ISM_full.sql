    PROCEDURE T_AU_EXCEPTION_REPORT(
        E_ID      IN NUMBER,
        P_NO      IN NUMBER,
        ENT_ID    IN NUMBER,
        R_ID      IN NUMBER,
        T_CURSOR  OUT T_CURSOR)
    IS
    BEGIN
        OPEN T_CURSOR FOR
            SELECT H.IID_REPORT_ID AS R_ID,
                   H.REPORT_TITLE,
                   H.DISCRIPTION,
                   H.LOAN_STATUS,
                   H.IND,
                   H.REPORTING_PERIOD,
                   CAST(NULL AS NUMBER) AS EXCEPTION_COUNT
              FROM T_AU_IID_EXCEPTION_REPORT_HDR H
             WHERE H.IS_ACTIVE = 'Y'
               AND EXISTS (
                    SELECT 1
                      FROM T_AU_IID_EXCEPTION_REPORT_ENTITY E
                     WHERE E.R_ID = H.IID_REPORT_ID
                       AND E.ENTITY_ID = ENT_ID
                       AND E.IS_ACTIVE = 'Y')
               AND EXISTS (
                    SELECT 1
                      FROM T_AU_IID_EXCEPTION_REPORT_ROLE RR
                     WHERE RR.R_ID = H.IID_REPORT_ID
                       AND RR.ROLE_ID = R_ID
                       AND RR.IS_ACTIVE = 'Y')
             ORDER BY NVL(H.SORT_ORDER,999999), H.REPORT_TITLE;

        LOG_RUN('T_AU_EXCEPTION_REPORT', NULL, E_ID, NULL, NULL, NULL, P_NO, ENT_ID, R_ID, 'SUCCESS', NULL, NULL);
    EXCEPTION
        WHEN OTHERS THEN
            LOG_RUN('T_AU_EXCEPTION_REPORT', NULL, E_ID, NULL, NULL, NULL, P_NO, ENT_ID, R_ID, 'FAILED', NULL, SQLERRM);
            RAISE;
    END T_AU_EXCEPTION_REPORT;

    PROCEDURE ENSURE_REPORT_ACCESS(
        P_REPORT_ID  IN NUMBER,
        P_ENT_ID     IN NUMBER,
        P_ROLE_ID    IN NUMBER,
        P_P_NO       IN NUMBER)
    IS
    BEGIN
        IF P_ENT_ID IS NOT NULL THEN
            MERGE INTO T_AU_IID_EXCEPTION_REPORT_ENTITY T
            USING (SELECT P_REPORT_ID AS R_ID, P_ENT_ID AS ENTITY_ID FROM DUAL) S
               ON (T.R_ID = S.R_ID AND T.ENTITY_ID = S.ENTITY_ID)
            WHEN MATCHED THEN
                UPDATE SET T.IS_ACTIVE = 'Y',
                           T.UPDATED_BY = NVL(P_P_NO, 0),
                           T.UPDATED_ON = SYSDATE
            WHEN NOT MATCHED THEN
                INSERT (MAP_ID, R_ID, ENTITY_ID, IS_ACTIVE, CREATED_BY, CREATED_ON)
                VALUES (SEQ_T_AU_IID_EXC_RPT_ENTITY.NEXTVAL, S.R_ID, S.ENTITY_ID, 'Y', NVL(P_P_NO, 0), SYSDATE);
        END IF;

        IF P_ROLE_ID IS NOT NULL THEN
            MERGE INTO T_AU_IID_EXCEPTION_REPORT_ROLE T
            USING (SELECT P_REPORT_ID AS R_ID, P_ROLE_ID AS ROLE_ID FROM DUAL) S
               ON (T.R_ID = S.R_ID AND T.ROLE_ID = S.ROLE_ID)
            WHEN MATCHED THEN
                UPDATE SET T.IS_ACTIVE = 'Y',
                           T.UPDATED_BY = NVL(P_P_NO, 0),
                           T.UPDATED_ON = SYSDATE
            WHEN NOT MATCHED THEN
                INSERT (MAP_ID, R_ID, ROLE_ID, IS_ACTIVE, CREATED_BY, CREATED_ON)
                VALUES (SEQ_T_AU_IID_EXC_RPT_ROLE.NEXTVAL, S.R_ID, S.ROLE_ID, 'Y', NVL(P_P_NO, 0), SYSDATE);
        END IF;
    END ENSURE_REPORT_ACCESS;

    PROCEDURE P_ADD_NEW_EXP_REPORT(
        P_IND           IN VARCHAR2,
        P_REPORT_ID     IN NUMBER,
        P_REPORT_TITLE  IN VARCHAR2,
        P_DESCRIPTION   IN VARCHAR2,
        P_R_TYPE        IN VARCHAR2,
        P_L_STATUS      IN NUMBER,
        P_P_NO          IN NUMBER,
        P_R_ID          IN NUMBER,
        P_ENT_ID        IN NUMBER,
        IO_CURSOR       OUT T_CURSOR)
    IS
        V_REPORT_ID   NUMBER := NVL(P_REPORT_ID, 0);
        V_SORT_ORDER  NUMBER := 0;
        V_EXISTS      NUMBER := 0;
        V_REMARKS     VARCHAR2(200);
    BEGIN
        IF TRIM(P_REPORT_TITLE) IS NULL THEN
            OPEN IO_CURSOR FOR SELECT 'Report title is required.' AS REMARKS FROM DUAL;
            RETURN;
        END IF;

        IF UPPER(NVL(TRIM(P_IND), 'A')) = 'A' OR V_REPORT_ID <= 0 THEN
            SELECT NVL(MAX(SORT_ORDER), 0) + 1
              INTO V_SORT_ORDER
              FROM T_AU_IID_EXCEPTION_REPORT_HDR;

            V_REPORT_ID := SEQ_T_AU_IID_EXC_RPT_HDR.NEXTVAL;

            INSERT INTO T_AU_IID_EXCEPTION_REPORT_HDR
                (IID_REPORT_ID, REPORT_CODE, REPORT_TITLE, DISCRIPTION, IND, LOAN_STATUS, REPORTING_PERIOD, SORT_ORDER, IS_ACTIVE, CREATED_BY, CREATED_ON)
            VALUES
                (V_REPORT_ID,
                 'IID_EXC_' || TO_CHAR(V_REPORT_ID),
                 TRIM(P_REPORT_TITLE),
                 P_DESCRIPTION,
                 UPPER(NVL(TRIM(P_R_TYPE), 'L')),
                 TO_CHAR(NVL(P_L_STATUS, 0)),
                 NULL,
                 V_SORT_ORDER,
                 'Y',
                 NVL(P_P_NO, 0),
                 SYSDATE);

            ENSURE_REPORT_ACCESS(V_REPORT_ID, P_ENT_ID, P_R_ID, P_P_NO);
            V_REMARKS := 'Report Added';
        ELSE
            SELECT COUNT(*)
              INTO V_EXISTS
              FROM T_AU_IID_EXCEPTION_REPORT_HDR
             WHERE IID_REPORT_ID = V_REPORT_ID;

            IF V_EXISTS = 0 THEN
                OPEN IO_CURSOR FOR SELECT 'Report not found.' AS REMARKS FROM DUAL;
                RETURN;
            END IF;

            UPDATE T_AU_IID_EXCEPTION_REPORT_HDR
               SET REPORT_TITLE = TRIM(P_REPORT_TITLE),
                   DISCRIPTION = P_DESCRIPTION,
                   IND = UPPER(NVL(TRIM(P_R_TYPE), 'L')),
                   LOAN_STATUS = TO_CHAR(NVL(P_L_STATUS, 0)),
                   IS_ACTIVE = 'Y',
                   UPDATED_BY = NVL(P_P_NO, 0),
                   UPDATED_ON = SYSDATE
             WHERE IID_REPORT_ID = V_REPORT_ID;

            ENSURE_REPORT_ACCESS(V_REPORT_ID, P_ENT_ID, P_R_ID, P_P_NO);
            V_REMARKS := 'Report Updated';
        END IF;

        OPEN IO_CURSOR FOR SELECT V_REMARKS AS REMARKS FROM DUAL;
        LOG_RUN('P_ADD_NEW_EXP_REPORT', V_REPORT_ID, NULL, NULL, NULL, NULL, P_P_NO, P_ENT_ID, P_R_ID, 'SUCCESS', NULL, NULL);
    EXCEPTION
        WHEN OTHERS THEN
            LOG_RUN('P_ADD_NEW_EXP_REPORT', V_REPORT_ID, NULL, NULL, NULL, NULL, P_P_NO, P_ENT_ID, P_R_ID, 'FAILED', NULL, SQLERRM);
            OPEN IO_CURSOR FOR SELECT SUBSTR(SQLERRM, 1, 2000) AS REMARKS FROM DUAL;
    END P_ADD_NEW_EXP_REPORT;


CREATE OR REPLACE PACKAGE BODY PKG_ISM AS

    FUNCTION GET_SOURCE_SQL(P_SOURCE_CODE IN VARCHAR2, P_SOURCE_TYPE OUT VARCHAR2, P_SOURCE_NAME OUT VARCHAR2)
        RETURN CLOB
    IS
        V_SQL CLOB;
    BEGIN
        SELECT SOURCE_TYPE, SOURCE_NAME, SOURCE_SQL
          INTO P_SOURCE_TYPE, P_SOURCE_NAME, V_SQL
          FROM T_AU_IID_EXC_SOURCE_CFG
         WHERE SOURCE_CODE = P_SOURCE_CODE
           AND IS_ACTIVE = 'Y';

        IF P_SOURCE_TYPE IN ('VIEW', 'TABLE') THEN
            RETURN 'SELECT * FROM ' || P_SOURCE_NAME;
        END IF;

        RETURN V_SQL;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            P_SOURCE_TYPE := NULL;
            P_SOURCE_NAME := NULL;
            RETURN NULL;
    END GET_SOURCE_SQL;

    PROCEDURE LOG_RUN(
        P_PROC_NAME      IN VARCHAR2,
        P_REPORT_ID      IN NUMBER   DEFAULT NULL,
        P_ENG_ID         IN NUMBER   DEFAULT NULL,
        P_ACCOUNT_NO     IN VARCHAR2 DEFAULT NULL,
        P_LOAN_DISB_ID   IN VARCHAR2 DEFAULT NULL,
        P_IMAGE_ID       IN NUMBER   DEFAULT NULL,
        P_P_NO           IN NUMBER   DEFAULT NULL,
        P_ENT_ID         IN NUMBER   DEFAULT NULL,
        P_R_ID           IN NUMBER   DEFAULT NULL,
        P_STATUS         IN VARCHAR2,
        P_ROWS_RETURNED  IN NUMBER   DEFAULT NULL,
        P_ERROR_TEXT     IN VARCHAR2 DEFAULT NULL)
    IS
    BEGIN
        INSERT INTO T_AU_IID_EXC_RUN_LOG
            (RUN_ID, PROC_NAME, REPORT_ID, ENG_ID, ACCOUNT_NO, LOAN_DISB_ID, IMAGE_ID, P_NO, ENT_ID, R_ID, STATUS, ROWS_RETURNED, ERROR_TEXT)
        VALUES
            (SEQ_T_AU_IID_EXC_RUN_LOG.NEXTVAL, P_PROC_NAME, P_REPORT_ID, P_ENG_ID, P_ACCOUNT_NO, P_LOAN_DISB_ID, P_IMAGE_ID, P_P_NO, P_ENT_ID, P_R_ID, P_STATUS, P_ROWS_RETURNED, SUBSTR(P_ERROR_TEXT,1,2000));
    EXCEPTION

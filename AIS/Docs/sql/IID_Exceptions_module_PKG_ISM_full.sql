-- Safe drop for reruns
-------------------------------------------------------------------------------
BEGIN
    FOR X IN (
        SELECT 'PACKAGE PKG_ISM' AS DDL_TEXT FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_RUN_LOG CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_SOURCE_HIST CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_ROLE_HIST CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_ENTITY_HIST CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_FORMAT_HIST CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_REPORT_HIST CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXC_SOURCE_CFG CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXCEPTION_REPORT_ROLE CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXCEPTION_REPORT_ENTITY CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXCEPTION_REPORT_FORMAT CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'TABLE T_AU_IID_EXCEPTION_REPORT_HDR CASCADE CONSTRAINTS PURGE' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_RUN_LOG' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_SOURCE_HIST' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_ROLE_HIST' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_ENTITY_HIST' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_FORMAT_HIST' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_REPORT_HIST' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_SOURCE_CFG' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_RPT_ROLE' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_RPT_ENTITY' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_RPT_FORMAT' FROM DUAL
        UNION ALL SELECT 'SEQUENCE SEQ_T_AU_IID_EXC_RPT_HDR' FROM DUAL
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP ' || X.DDL_TEXT;
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE NOT IN (-4043, -942, -2289) THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;

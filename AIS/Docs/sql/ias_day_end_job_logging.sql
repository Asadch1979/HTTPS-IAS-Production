-- Day-end job instrumentation; deliberately separate from generic scheduler metadata.
-- Changes record counts only, never employee or session details.
CREATE TABLE T_IAS_DAY_END_RUN
(
    RUN_ID               NUMBER NOT NULL,
    IAS_EXECUTION_ID     NUMBER,
    STATUS               VARCHAR2(30) NOT NULL,
    STARTED_ON           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_ON         TIMESTAMP WITH TIME ZONE,
    TOTAL_ROWS_AFFECTED  NUMBER,
    ERROR_MESSAGE        VARCHAR2(4000),
    CONSTRAINT PK_IAS_DAY_END_RUN PRIMARY KEY (RUN_ID),
    CONSTRAINT UQ_IAS_DAY_END_IAS_EXEC UNIQUE (IAS_EXECUTION_ID),
    CONSTRAINT FK_IAS_DAY_END_IAS_EXEC FOREIGN KEY (IAS_EXECUTION_ID)
        REFERENCES T_IAS_JOB_EXECUTION (EXECUTION_ID),
    CONSTRAINT CK_IAS_DAY_END_RUN_STATUS CHECK
        (STATUS IN ('RUNNING', 'SUCCESS', 'FAILED', 'RECONCILIATION_REQUIRED'))
);
CREATE SEQUENCE SEQ_IAS_DAY_END_RUN START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;
CREATE TABLE T_IAS_DAY_END_STEP
(
    STEP_ID            NUMBER NOT NULL,
    RUN_ID             NUMBER NOT NULL,
    STEP_CODE          VARCHAR2(50) NOT NULL,
    ACTION_TYPE        VARCHAR2(10) NOT NULL,
    STARTED_ON         TIMESTAMP WITH TIME ZONE NOT NULL,
    COMPLETED_ON       TIMESTAMP WITH TIME ZONE NOT NULL,
    ROWS_AFFECTED      NUMBER NOT NULL,
    STATUS             VARCHAR2(20) NOT NULL,
    ERROR_MESSAGE      VARCHAR2(2000),
    CONSTRAINT PK_IAS_DAY_END_STEP PRIMARY KEY (STEP_ID),
    CONSTRAINT FK_IAS_DAY_END_STEP_RUN FOREIGN KEY (RUN_ID)
        REFERENCES T_IAS_DAY_END_RUN (RUN_ID),
    CONSTRAINT UQ_IAS_DAY_END_STEP UNIQUE (RUN_ID, STEP_CODE),
    CONSTRAINT CK_IAS_DAY_END_STEP_ACTION CHECK
        (ACTION_TYPE IN ('UPDATE', 'DELETE', 'INSERT')),
    CONSTRAINT CK_IAS_DAY_END_STEP_STATUS CHECK
        (STATUS IN ('APPLIED', 'COMMITTED', 'ROLLED_BACK', 'FAILED')),
    CONSTRAINT CK_IAS_DAY_END_STEP_COUNT CHECK (ROWS_AFFECTED >= 0)
);
CREATE SEQUENCE SEQ_IAS_DAY_END_STEP START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;
CREATE INDEX IX_IAS_DAY_END_RUN_STARTED ON T_IAS_DAY_END_RUN (STARTED_ON);
CREATE INDEX IX_IAS_DAY_END_STEP_RUN ON T_IAS_DAY_END_STEP (RUN_ID);

-- Run summaries and the corresponding scheduler execution outcome.
SELECT R.RUN_ID,
       R.IAS_EXECUTION_ID,
       R.STATUS AS DAY_END_STATUS,
       E.STATUS AS SCHEDULER_STATUS,
       R.STARTED_ON,
       R.COMPLETED_ON,
       R.TOTAL_ROWS_AFFECTED,
       R.ERROR_MESSAGE
  FROM T_IAS_DAY_END_RUN R
  LEFT JOIN T_IAS_JOB_EXECUTION E ON E.EXECUTION_ID = R.IAS_EXECUTION_ID
 ORDER BY R.RUN_ID DESC;

-- Exact statement-level counts and timings (the seven DML operations).
SELECT R.RUN_ID,
       R.IAS_EXECUTION_ID,
       S.STEP_CODE,
       S.ACTION_TYPE,
       S.ROWS_AFFECTED,
       S.STARTED_ON,
       S.COMPLETED_ON,
       S.STATUS,
       S.ERROR_MESSAGE
  FROM T_IAS_DAY_END_STEP S
  JOIN T_IAS_DAY_END_RUN R ON R.RUN_ID = S.RUN_ID
 ORDER BY S.STEP_ID DESC;

DECLARE
    v_admin_menu_id NUMBER;
    v_page_id NUMBER;

    PROCEDURE ensure_page(p_name VARCHAR2, p_path VARCHAR2, p_order NUMBER) IS
    BEGIN
        SELECT MAX(ID)
          INTO v_page_id
          FROM T_MENU_PAGES
         WHERE LOWER(TRIM(PAGE_PATH)) = LOWER(TRIM(p_path));

        IF v_page_id IS NULL THEN
            SELECT NVL(MAX(ID), 0) + 1 INTO v_page_id FROM T_MENU_PAGES;
            INSERT INTO T_MENU_PAGES
                (ID, MENU_ID, PAGE_NAME, PAGE_PATH, PAGE_ORDER, STATUS, HIDE_MENU, PAGE_KEY, PAGE_URL)
            VALUES
                (v_page_id, v_admin_menu_id, p_name, p_path, p_order, 'A', 1, UPPER(REPLACE(p_path, '/', '_')), '/' || p_path);
        ELSE
            UPDATE T_MENU_PAGES
               SET MENU_ID = v_admin_menu_id,
                   PAGE_NAME = p_name,
                   STATUS = 'A',
                   HIDE_MENU = 1,
                   PAGE_KEY = UPPER(REPLACE(p_path, '/', '_')),
                   PAGE_URL = '/' || p_path
             WHERE ID = v_page_id;
        END IF;

        MERGE INTO T_MENU_PAGES_GROUPMAP gm
        USING (SELECT 1 GROUP_ID, v_page_id PAGE_ID FROM dual) src
        ON (gm.GROUP_ID = src.GROUP_ID AND gm.PAGE_ID = src.PAGE_ID)
        WHEN NOT MATCHED THEN INSERT (GROUPMAP_ID, GROUP_ID, PAGE_ID)
            VALUES ((SELECT NVL(MAX(GROUPMAP_ID), 0) + 1 FROM T_MENU_PAGES_GROUPMAP), src.GROUP_ID, src.PAGE_ID);
    END;
BEGIN
    SELECT MIN(MENU_ID)
      INTO v_admin_menu_id
      FROM T_MENU
     WHERE UPPER(MENU_NAME) IN ('ADMIN', 'ADMINISTRATION');

    IF v_admin_menu_id IS NULL THEN
        SELECT MIN(MENU_ID) INTO v_admin_menu_id FROM T_MENU;
    END IF;

    ensure_page('System Error Monitoring', 'AdministrationPanel/SystemErrorMonitoring', 9991);
    ensure_page('System Error Detail', 'AdministrationPanel/SystemErrorDetail', 9992);
    ensure_page('Get System Errors', 'AdministrationPanel/GetSystemErrors', 9993);
    ensure_page('Resolve System Error', 'AdministrationPanel/ResolveSystemError', 9994);
    ensure_page('Export System Errors', 'AdministrationPanel/ExportSystemErrors', 9995);
END;

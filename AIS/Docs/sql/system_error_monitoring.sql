-- IAS centralized system error monitoring tables and seed data.
-- Deploy this script, then deploy AIS/Docs/sql/PKG_LG.sql so the package
-- exposes REGISTER_SYSTEM_ERROR, MARK_SYSTEM_ERROR_EMAIL, and
-- GET_SYSTEM_ERROR_RECIPIENTS.

CREATE TABLE T_AU_SYSTEM_ERROR_MASTER
(
    ERROR_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ERROR_REFERENCE       VARCHAR2(50) NOT NULL,
    FINGERPRINT           VARCHAR2(128) NOT NULL,
    ERROR_TYPE            VARCHAR2(300),
    ERROR_CODE            VARCHAR2(100),
    MODULE                VARCHAR2(100),
    CONTROLLER            VARCHAR2(100),
    ACTION                VARCHAR2(100),
    API_PATH              VARCHAR2(1000),
    STORED_PROCEDURE      VARCHAR2(200),
    PPNO                  VARCHAR2(50),
    ROLE_NAME             VARCHAR2(150),
    ENTITY_NAME           VARCHAR2(300),
    PAGE_ID               NUMBER,
    ENG_ID                NUMBER,
    PARA_ID               NUMBER,
    COM_ID                NUMBER,
    FIRST_OCCURRENCE_UTC  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LAST_OCCURRENCE_UTC   TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    OCCURRENCE_COUNT      NUMBER DEFAULT 1 NOT NULL,
    LAST_TRACE_ID         VARCHAR2(200),
    LAST_IP_ADDRESS       VARCHAR2(100),
    ERROR_MESSAGE         CLOB,
    TECHNICAL_DETAILS     CLOB,
    EMAIL_SENT            CHAR(1) DEFAULT 'N' CHECK (EMAIL_SENT IN ('Y','N')),
    EMAIL_SENT_UTC        TIMESTAMP,
    RESOLUTION_STATUS     VARCHAR2(30) DEFAULT 'OPEN' NOT NULL,
    RESOLVED_BY           VARCHAR2(100),
    RESOLVED_ON_UTC       TIMESTAMP,
    RESOLUTION_REMARKS    VARCHAR2(1000),
    CONSTRAINT UK_AU_SYS_ERR_MASTER_FP UNIQUE (FINGERPRINT),
    CONSTRAINT UK_AU_SYS_ERR_MASTER_REF UNIQUE (ERROR_REFERENCE)
);

CREATE TABLE T_AU_SYSTEM_ERROR_HISTORY
(
    HISTORY_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ERROR_ID           NUMBER NOT NULL,
    OCCURRED_ON_UTC    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    TRACE_ID           VARCHAR2(200),
    IP_ADDRESS         VARCHAR2(100),
    USER_AGENT         VARCHAR2(1000),
    PPNO               VARCHAR2(50),
    ROLE_NAME          VARCHAR2(150),
    ENTITY_NAME        VARCHAR2(300),
    PAGE_ID            NUMBER,
    ENG_ID             NUMBER,
    PARA_ID            NUMBER,
    COM_ID             NUMBER,
    API_PATH           VARCHAR2(1000),
    ERROR_MESSAGE      CLOB,
    TECHNICAL_DETAILS  CLOB,
    CONSTRAINT FK_AU_SYS_ERR_HIST_MASTER FOREIGN KEY (ERROR_ID)
        REFERENCES T_AU_SYSTEM_ERROR_MASTER (ERROR_ID)
);

CREATE INDEX IX_AU_SYS_ERR_HIST_ERROR_ID ON T_AU_SYSTEM_ERROR_HISTORY (ERROR_ID, OCCURRED_ON_UTC);

CREATE TABLE T_AU_SYSTEM_ERROR_RECIPIENTS
(
    RECIPIENT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RECIPIENT_TYPE  VARCHAR2(10) NOT NULL CHECK (RECIPIENT_TYPE IN ('TO','CC')),
    EMAIL_ADDRESS   VARCHAR2(320) NOT NULL,
    DISPLAY_NAME    VARCHAR2(200),
    IS_ACTIVE       CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
    SORT_ORDER      NUMBER DEFAULT 100 NOT NULL,
    CREATED_ON_UTC  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
);

CREATE UNIQUE INDEX UX_AU_SYS_ERR_RECIP_EMAIL
    ON T_AU_SYSTEM_ERROR_RECIPIENTS (LOWER(EMAIL_ADDRESS), RECIPIENT_TYPE);

MERGE INTO T_AU_SYSTEM_ERROR_RECIPIENTS tgt
USING (
    SELECT 'TO' RECIPIENT_TYPE, 'asma.latif@ztbl.com.pk' EMAIL_ADDRESS, 'Primary Admin' DISPLAY_NAME, 10 SORT_ORDER FROM dual
    UNION ALL SELECT 'TO', 'arslan.139986@ztbl.com.pk', 'Secondary Admin', 20 FROM dual
    UNION ALL SELECT 'CC', 'svp.isad@ztbl.com.pk', 'Super Admin', 30 FROM dual
) src
ON (LOWER(tgt.EMAIL_ADDRESS) = LOWER(src.EMAIL_ADDRESS) AND tgt.RECIPIENT_TYPE = src.RECIPIENT_TYPE)
WHEN MATCHED THEN UPDATE SET
    tgt.DISPLAY_NAME = src.DISPLAY_NAME,
    tgt.IS_ACTIVE = 'Y',
    tgt.SORT_ORDER = src.SORT_ORDER
WHEN NOT MATCHED THEN INSERT (RECIPIENT_TYPE, EMAIL_ADDRESS, DISPLAY_NAME, IS_ACTIVE, SORT_ORDER)
    VALUES (src.RECIPIENT_TYPE, src.EMAIL_ADDRESS, src.DISPLAY_NAME, 'Y', src.SORT_ORDER);

DECLARE
  PROCEDURE UPSERT_JOB(P_NAME VARCHAR2,P_ACTION VARCHAR2,P_SCHEDULE VARCHAR2,P_COMMENTS VARCHAR2) IS
    V_COUNT NUMBER; V_START TIMESTAMP WITH TIME ZONE;
  BEGIN
    DBMS_SCHEDULER.EVALUATE_CALENDAR_STRING(P_SCHEDULE,SYSTIMESTAMP,SYSTIMESTAMP,V_START);
    SELECT COUNT(*) INTO V_COUNT FROM USER_SCHEDULER_JOBS WHERE JOB_NAME=UPPER(P_NAME);
    IF V_COUNT=0 THEN
      DBMS_SCHEDULER.CREATE_JOB(JOB_NAME=>P_NAME,JOB_TYPE=>'PLSQL_BLOCK',JOB_ACTION=>P_ACTION,
        START_DATE=>V_START,REPEAT_INTERVAL=>P_SCHEDULE,ENABLED=>TRUE,AUTO_DROP=>FALSE,COMMENTS=>P_COMMENTS);
    ELSE
      DBMS_SCHEDULER.DISABLE(P_NAME,FORCE=>TRUE);
      DBMS_SCHEDULER.SET_ATTRIBUTE(P_NAME,'job_action',P_ACTION);
      DBMS_SCHEDULER.SET_ATTRIBUTE(P_NAME,'repeat_interval',P_SCHEDULE);
      DBMS_SCHEDULER.SET_ATTRIBUTE(P_NAME,'comments',P_COMMENTS);
      DBMS_SCHEDULER.ENABLE(P_NAME);
    END IF;
  END;
BEGIN
  FOR R IN (
    SELECT JOB_NAME FROM USER_SCHEDULER_JOBS
     WHERE JOB_NAME='JOB_MGMT_AUDIT_WEEKLY_NOTIFY'
        OR UPPER(JOB_ACTION) LIKE '%SEND_MGMT_AUDIT_WEEKLY%'
  ) LOOP
    DBMS_SCHEDULER.DROP_JOB(R.JOB_NAME,FORCE=>TRUE);
  END LOOP;
  UPSERT_JOB('JOB_MGMT_AUDIT_MAPPING_EXCEPT','BEGIN PKG_IAS_NOTIFICATION.SEND_MGMT_AUDIT_MAPPING_EXCEPTIONS; END;',
    '&MGMT_MAPPING_EXCEPTION_SCHEDULE','Queues Friday mapping exceptions separately for heads 112242 and 112248.');
  UPSERT_JOB('JOB_IAS_NOTIFICATION_HEALTH','BEGIN PKG_IAS_NOTIFICATION.SEND_NOTIFICATION_HEALTH; END;',
    '&IAS_NOTIFICATION_HEALTH_SCHEDULE','Queues the IAS notification operational health report for Super Admin.');
END;

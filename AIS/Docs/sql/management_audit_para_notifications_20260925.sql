DECLARE
  V_MASTER NUMBER; V_PACKAGE NUMBER; V_QUEUE_API NUMBER; V_MAPPED NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_MASTER FROM USER_OBJECTS
   WHERE OBJECT_NAME='IAS_NOTIFICATION_MASTER' AND OBJECT_TYPE='TABLE' AND STATUS='VALID';
  SELECT COUNT(*) INTO V_PACKAGE FROM USER_OBJECTS
   WHERE OBJECT_NAME='PKG_IAS_NOTIFICATION' AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY') AND STATUS='VALID';
  SELECT COUNT(*) INTO V_QUEUE_API FROM USER_PROCEDURES
   WHERE OBJECT_NAME='PKG_INQ' AND PROCEDURE_NAME='P_ENQUEUE_EMAIL';
  IF V_MASTER<>1 OR V_PACKAGE<>2 OR V_QUEUE_API<>1 THEN
    RAISE_APPLICATION_ERROR(-20801,'IAS_NOTIFICATION_MASTER / PKG_IAS_NOTIFICATION / PKG_INQ queue architecture is not active.');
  END IF;

  SELECT COUNT(*) INTO V_MAPPED FROM (
    SELECT DISTINCT E.ENTITY_ID
      FROM T_AUDITEE_ENTITIES E
      JOIN T_AUDITEE_ENTITIES_MAPING M ON M.ENTITY_ID=E.ENTITY_ID
      JOIN T_AUDITEE_ENTITIES D ON D.ENTITY_ID=M.DIV_OFFICE
      JOIN T_AUDITEE_ENTITIES R ON R.ENTITY_ID=NVL(M.REPORTING,M.B_GROUP)
     WHERE E.AUDITBY_ID IN (112242,112248)
       AND TRIM(D.EMAIL_ADDRESS) IS NOT NULL AND TRIM(R.EMAIL_ADDRESS) IS NOT NULL);
  IF V_MAPPED<3 THEN
    RAISE_APPLICATION_ERROR(-20802,'Fewer than three Management Audit entities have demonstrable Division/Reporting recipient mappings.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Confirmed central master/package/queue architecture.');
  FOR R IN (
    SELECT * FROM (
      SELECT DISTINCT E.ENTITY_ID,E.NAME ENTITY_NAME,D.ENTITY_ID DIVISION_ID,D.NAME DIVISION_NAME,
             D.EMAIL_ADDRESS DIVISION_EMAIL,RPT.ENTITY_ID REPORTING_ID,RPT.NAME REPORTING_NAME,
             RPT.EMAIL_ADDRESS REPORTING_EMAIL
        FROM T_AUDITEE_ENTITIES E
        JOIN T_AUDITEE_ENTITIES_MAPING M ON M.ENTITY_ID=E.ENTITY_ID
        JOIN T_AUDITEE_ENTITIES D ON D.ENTITY_ID=M.DIV_OFFICE
        JOIN T_AUDITEE_ENTITIES RPT ON RPT.ENTITY_ID=NVL(M.REPORTING,M.B_GROUP)
       WHERE E.AUDITBY_ID IN (112242,112248)
         AND TRIM(D.EMAIL_ADDRESS) IS NOT NULL AND TRIM(RPT.EMAIL_ADDRESS) IS NOT NULL
       ORDER BY E.ENTITY_ID) WHERE ROWNUM<=3
  ) LOOP
    DBMS_OUTPUT.PUT_LINE('Entity ['||R.ENTITY_ID||'] '||R.ENTITY_NAME||' -> Division ['||R.DIVISION_ID||'] '||
      R.DIVISION_NAME||' <'||R.DIVISION_EMAIL||'> -> Reporting/Group ['||R.REPORTING_ID||'] '||
      R.REPORTING_NAME||' <'||R.REPORTING_EMAIL||'>');
  END LOOP;
END;

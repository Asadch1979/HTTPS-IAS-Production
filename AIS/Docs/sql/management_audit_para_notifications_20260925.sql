PROMPT === Scheduler: Mondays 07:00 database-server time ===
DECLARE
  V_COUNT NUMBER;
  V_START TIMESTAMP WITH TIME ZONE := TRUNC(SYSTIMESTAMP,'IW') + INTERVAL '7' DAY + INTERVAL '7' HOUR;
BEGIN
  SELECT COUNT(*) INTO V_COUNT FROM USER_SCHEDULER_JOBS WHERE JOB_NAME='JOB_MGMT_AUDIT_WEEKLY_NOTIFY';
  IF V_COUNT=0 THEN
    DBMS_SCHEDULER.CREATE_JOB(JOB_NAME=>'JOB_MGMT_AUDIT_WEEKLY_NOTIFY',JOB_TYPE=>'PLSQL_BLOCK',
      JOB_ACTION=>'BEGIN PKG_IAS_NOTIFICATION.SEND_MGMT_AUDIT_WEEKLY; END;',START_DATE=>V_START,
      REPEAT_INTERVAL=>'FREQ=WEEKLY;BYDAY=MON;BYHOUR=07;BYMINUTE=00;BYSECOND=00',ENABLED=>TRUE,AUTO_DROP=>FALSE,
      COMMENTS=>'Queues the previous Monday-Sunday Management Audit settled/rejected digest.');
  ELSE
    DBMS_SCHEDULER.DISABLE('JOB_MGMT_AUDIT_WEEKLY_NOTIFY',FORCE=>TRUE);
    DBMS_SCHEDULER.SET_ATTRIBUTE('JOB_MGMT_AUDIT_WEEKLY_NOTIFY','job_action','BEGIN PKG_IAS_NOTIFICATION.SEND_MGMT_AUDIT_WEEKLY; END;');
    DBMS_SCHEDULER.SET_ATTRIBUTE('JOB_MGMT_AUDIT_WEEKLY_NOTIFY','repeat_interval','FREQ=WEEKLY;BYDAY=MON;BYHOUR=07;BYMINUTE=00;BYSECOND=00');
    DBMS_SCHEDULER.ENABLE('JOB_MGMT_AUDIT_WEEKLY_NOTIFY');
  END IF;
END;

DECLARE
  V_OBJECTS NUMBER; V_ACTIVE NUMBER; V_MAPPED NUMBER; V_CONFLICTS NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_OBJECTS FROM USER_OBJECTS
   WHERE OBJECT_NAME IN ('IAS_NOTIFICATION_MASTER','PKG_IAS_NOTIFICATION','V_IAS_POST_COMPLIANCE_NOTIFY') AND STATUS='VALID';
  SELECT COUNT(*) INTO V_ACTIVE FROM IAS_NOTIFICATION_MASTER
   WHERE NOTIFICATION_CODE='PARA_STATUS_UPDATED' AND IS_ACTIVE='Y';
  IF V_OBJECTS<>4 OR V_ACTIVE<>1 THEN
    RAISE_APPLICATION_ERROR(-20801,'Central IAS notification architecture is not active; deployment stopped.');
  END IF;
  SELECT COUNT(*) INTO V_MAPPED FROM (
    SELECT DISTINCT E.ENTITY_ID FROM T_AUDITEE_ENTITIES E
    JOIN T_AUDITEE_ENTITIES_MAPING M ON M.ENTITY_ID=E.ENTITY_ID
    JOIN T_AUDITEE_ENTITIES D ON D.ENTITY_ID=M.DIV_OFFICE
    JOIN T_AUDITEE_ENTITIES G ON G.ENTITY_ID=M.B_GROUP
    WHERE E.AUDITBY_ID IN (112242,112248)
      AND TRIM(D.EMAIL_ADDRESS) IS NOT NULL AND TRIM(G.EMAIL_ADDRESS) IS NOT NULL);
  IF V_MAPPED<3 THEN RAISE_APPLICATION_ERROR(-20802,'Fewer than three Management Audit entities have explicit Division/Group recipient mappings.'); END IF;
  SELECT COUNT(*) INTO V_CONFLICTS FROM (
    SELECT M.ENTITY_ID FROM T_AUDITEE_ENTITIES_MAPING M
    JOIN T_AUDITEE_ENTITIES E ON E.ENTITY_ID=M.ENTITY_ID
    WHERE E.AUDITBY_ID IN (112242,112248)
    GROUP BY M.ENTITY_ID
    HAVING COUNT(DISTINCT TO_CHAR(M.DIV_OFFICE)||':'||TO_CHAR(M.B_GROUP))>1);
  IF V_CONFLICTS>0 THEN RAISE_APPLICATION_ERROR(-20803,'Conflicting DIV_OFFICE/B_GROUP mappings exist; deployment stopped.'); END IF;
  DBMS_OUTPUT.PUT_LINE('Verified deployed central architecture and explicit recipient mappings.');
  FOR R IN (
    SELECT * FROM (
      SELECT DISTINCT E.ENTITY_ID,E.NAME ENTITY_NAME,D.ENTITY_ID DIVISION_ID,D.NAME DIVISION_NAME,
             D.EMAIL_ADDRESS DIVISION_EMAIL,G.ENTITY_ID GROUP_ID,G.NAME GROUP_NAME,G.EMAIL_ADDRESS GROUP_EMAIL
      FROM T_AUDITEE_ENTITIES E
      JOIN T_AUDITEE_ENTITIES_MAPING M ON M.ENTITY_ID=E.ENTITY_ID
      JOIN T_AUDITEE_ENTITIES D ON D.ENTITY_ID=M.DIV_OFFICE
      JOIN T_AUDITEE_ENTITIES G ON G.ENTITY_ID=M.B_GROUP
      WHERE E.AUDITBY_ID IN (112242,112248)
        AND TRIM(D.EMAIL_ADDRESS) IS NOT NULL AND TRIM(G.EMAIL_ADDRESS) IS NOT NULL
      ORDER BY E.ENTITY_ID) WHERE ROWNUM<=3
  ) LOOP
    DBMS_OUTPUT.PUT_LINE('Entity ['||R.ENTITY_ID||'] '||R.ENTITY_NAME||' -> Division ['||R.DIVISION_ID||'] '||
      R.DIVISION_NAME||' <'||R.DIVISION_EMAIL||'> -> Group ['||R.GROUP_ID||'] '||R.GROUP_NAME||' <'||R.GROUP_EMAIL||'>');
  END LOOP;
END;

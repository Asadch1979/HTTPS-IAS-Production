-- Run as table owner AFTER reviewing preflight output, with ALL writers stopped.
-- Keep writers stopped through PKG_HD compilation. Oracle DDL commits release
-- table locks; this script cannot substitute for a maintenance window.
-- No historical rows, keys or constraints are changed.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET SERVEROUTPUT ON
DECLARE
  V_COUNT NUMBER;
  PROCEDURE ENSURE_SEQUENCE(P_SEQUENCE VARCHAR2, P_TABLE VARCHAR2) IS
    V_MAX_ID NUMBER;
    V_NEXT NUMBER;
    V_EXISTS NUMBER;
    V_INCREMENT NUMBER;
    V_CYCLE VARCHAR2(1);
  BEGIN
    -- Names are fixed below, not request input. Assert identifiers for DDL.
    EXECUTE IMMEDIATE 'SELECT NVL(MAX(ID),0) FROM ' || DBMS_ASSERT.SIMPLE_SQL_NAME(P_TABLE)
      INTO V_MAX_ID;
    SELECT COUNT(*) INTO V_EXISTS FROM USER_SEQUENCES WHERE SEQUENCE_NAME = P_SEQUENCE;
    IF V_EXISTS = 0 THEN
      EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || DBMS_ASSERT.SIMPLE_SQL_NAME(P_SEQUENCE) ||
        ' START WITH ' || TO_CHAR(GREATEST(TRUNC(V_MAX_ID) + 1, 1), 'TM9') ||
        ' INCREMENT BY 1 NOMAXVALUE NOCYCLE CACHE 20';
    END IF;
    SELECT INCREMENT_BY, CYCLE_FLAG INTO V_INCREMENT, V_CYCLE
      FROM USER_SEQUENCES WHERE SEQUENCE_NAME = P_SEQUENCE;
    IF V_INCREMENT <> 1 OR V_CYCLE <> 'N' THEN
      RAISE_APPLICATION_ERROR(-20154, 'Unexpected sequence configuration: ' || P_SEQUENCE);
    END IF;
    EXECUTE IMMEDIATE 'SELECT ' || DBMS_ASSERT.SIMPLE_SQL_NAME(P_SEQUENCE) || '.NEXTVAL FROM DUAL' INTO V_NEXT;
    IF V_NEXT <= V_MAX_ID THEN
      RAISE_APPLICATION_ERROR(-20155, 'Sequence is below historical IDs. DBA must advance (never reset) ' || P_SEQUENCE || ' above ' || TO_CHAR(V_MAX_ID, 'TM9'));
    END IF;
    DBMS_OUTPUT.PUT_LINE(P_SEQUENCE || ': verified above historical maximum ' || TO_CHAR(V_MAX_ID, 'TM9'));
  END;
BEGIN
  SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS
   WHERE CONSTRAINT_NAME = 'UQ_OBS_GIST' AND TABLE_NAME = 'T_AU_OBSERVATION_GIST'
     AND CONSTRAINT_TYPE IN ('U', 'P') AND STATUS = 'ENABLED' AND VALIDATED = 'VALIDATED';
  IF V_COUNT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20156, 'UQ_OBS_GIST must exist, be enabled and validated; inspect preflight.');
  END IF;
  SELECT COUNT(*) INTO V_COUNT FROM
    (SELECT OBS_ID FROM T_AU_OBSERVATION_GIST GROUP BY OBS_ID HAVING COUNT(*) > 1
     UNION ALL
     SELECT OBS_ID FROM T_AU_OBSERVATION_FINAL_RECCOMENDATION GROUP BY OBS_ID HAVING COUNT(*) > 1);
  IF V_COUNT <> 0 THEN
    RAISE_APPLICATION_ERROR(-20157, 'Historical duplicate observation records require investigation; no data changed.');
  END IF;
  ENSURE_SEQUENCE('SEQ_AU_OBSERVATION_GIST', 'T_AU_OBSERVATION_GIST');
  ENSURE_SEQUENCE('SEQ_AU_OBS_FINAL_RECOMM', 'T_AU_OBSERVATION_FINAL_RECCOMENDATION');
END;

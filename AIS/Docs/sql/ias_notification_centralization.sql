--------------------------------------------------------------------------------
MERGE INTO IAS_NOTIFICATION_MASTER D
USING (
  SELECT 'AUDIT_TEAM_ASSIGNED' CODE, 'Audit Task Assigned' NAME, 'Planning' MODL,
    'ApiCallsController.AddEngagementPlan' CALLER, 'PKG_PG.P_ADDAUDITENGPLAN' PROC,
    'Existing AddAuditEngagementPlan result + audit-team data source' SRC,
    'IAS Notification: Audit Task Assigned - {REFERENCE}' SUBJ, 'Audit Task Assigned' TITLE,
    'An audit task has been allocated to the assigned team. Please review the engagement details and proceed in line with the approved plan.' SUMMARY,
    'WORKFLOW' NT, 'N' ATT, 'Active application notification.' DESCR FROM DUAL UNION ALL
  SELECT 'AUDIT_TEAM_JOINED','Audit Team Joined','Audit','DBConnection.AddJoiningReport',
    'PKG_AR.P_ADDJOININGREPORT','PKG_AR.P_ADDJOININGREPORT output cursor',
    'IAS Notification: Audit Team has Joined for {REFERENCE}','Audit Team has Joined',
    'The audit team has officially joined. Please coordinate with the team and provide requested information.',
    'WORKFLOW','N','Use the procedure cursor; do not repeat its recipient/team lookups.' FROM DUAL UNION ALL
  SELECT 'OBS_SUBMITTED_AUDITEE','Observation Submitted to Auditee','Audit Execution',
    'ApiCallsController.submit_observation_to_auditee','PKG_AR observation submission process',
    'Existing managed-observation data source','IAS Notification: Observation Submitted to Auditee - {REFERENCE}',
    'Observation Submitted to Auditee','An audit observation has been submitted to the auditee for review and response.',
    'WORKFLOW','N','Active application notification.' FROM DUAL UNION ALL
  SELECT 'PARA_STATUS_UPDATED','Audit Para Status Updated','Compliance',
    'DBConnection.SubmitPostAuditComplianceReview','PKG_AE.P_SUBMITPOSTAUDITCOMPLIANCE_REVIEW',
    'V_GET_AIS_POST_COMPLIANCE','IAS Notification: Para No. {REFERENCE} is marked {STATUS}',
    'Audit Para Status Updated','Para No. {REFERENCE} has been marked as {STATUS}.',
    'WORKFLOW','N','V_GET_AIS_POST_COMPLIANCE is authoritative; recipient resolution is centralized below.' FROM DUAL UNION ALL
  SELECT 'FINAL_REPORT_ISSUED','Final Audit Report Issued','Reporting',
    'FieldAuditReportController finalization','PKG_FRPT final-report process',
    'Existing field-audit report overview data source','IAS Notification: Final Audit Report Issued - {REFERENCE}',
    'Final Audit Report Issued','The final audit report has been issued. The generated PDF is attached by the existing application process.',
    'WORKFLOW','Y','Application retains PDF attachment responsibility.' FROM DUAL UNION ALL
  SELECT 'INQUIRY_ASSIGNED_UNIT','Inquiry Assigned to I&I Unit','IID',
    'ApiCallsController.AddHeadReview','PKG_INQ.ADD_HEAD_REVIEW',
    'Existing complaint/head-review/unit data sources','IAS Notification: Inquiry Assigned to I&I Unit - {REFERENCE}',
    'Inquiry Assigned to I&I Unit','A complaint inquiry has been approved and allocated to the relevant I&I Unit.',
    'WORKFLOW','N','Active application notification.' FROM DUAL UNION ALL
  SELECT 'PASSWORD_RESET_SUCCESS','Password Reset Successful','Authentication',
    'DBConnection.ResetUserPassword','PKG_AD.RESET_USER_PASSWORD','V_SERVICE_EMPLOYEEINFO + RESET_USER_PASSWORD output cursor',
    'IAS~ Password Reset Successful','Password Reset Successful',
    'Your password has been successfully reset. Change the temporary password immediately after logging in.',
    'SECURITY','N','Temporary password must only be supplied by the reset process; it is never queried from storage.' FROM DUAL UNION ALL
  SELECT 'AUDIT_SAMPLE_ISSUE','Audit Sample Creation Issue','Sampling',
    'DBConnection.CreateSampleDataAfterEngagementApproval','PKG_SM.P_ADD_SAMPLE_DATA','PKG_SM.P_ADD_SAMPLE_DATA output cursor',
    'IAS~Notification: Issue in Audit Sample for Engagement ID: {REFERENCE}','Issue in Audit Sample Creation',
    'An issue was identified while creating the audit sample. Please review and resolve it.',
    'TECHNICAL','N','Use the existing procedure cursor recipients.' FROM DUAL UNION ALL
  SELECT 'AUDIT_EXCEPTION_ISSUE','Audit Exception Creation Issue','Exception Monitoring',
    'DBConnection.CreateExceptionDataAfterEngagementApproval','PKG_SM.P_ADD_EXCEPTION_DATA','PKG_SM.P_ADD_EXCEPTION_DATA output cursor',
    'IAS~Notification: Issue in Audit Exception for Engagement ID: {REFERENCE}','Issue in Audit Exception Creation',
    'An issue was identified while creating the audit exception report. Please review and resolve it.',
    'TECHNICAL','N','Use the existing procedure cursor recipients.' FROM DUAL UNION ALL

/*
  IAS CENTRAL NOTIFICATION MANAGEMENT
  ===================================
  Target: Oracle 19c+ / current IAS schema

  Reviewed notification inventory and current caller/source
  ---------------------------------------------------------
  1  AUDIT_TEAM_ASSIGNED        ApiCallsController.AddEngagementPlan / PKG_PG.P_ADDAUDITENGPLAN
  2  AUDIT_TEAM_JOINED          DBConnection.AddJoiningReport / PKG_AR.P_ADDJOININGREPORT
  3  OBS_SUBMITTED_AUDITEE      ApiCallsController.submit_observation_to_auditee / PKG_AR observation workflow
  4  PARA_STATUS_UPDATED        DBConnection.SubmitPostAuditComplianceReview / PKG_AE.P_SUBMITPOSTAUDITCOMPLIANCE_REVIEW
  5  FINAL_REPORT_ISSUED        FieldAuditReportController.Finalize / PKG_FRPT final-report process
  6  INQUIRY_ASSIGNED_UNIT      ApiCallsController.AddHeadReview / PKG_INQ.ADD_HEAD_REVIEW
  7  PASSWORD_RESET_SUCCESS     DBConnection.ResetUserPassword / PKG_AD.RESET_USER_PASSWORD
  8  AUDIT_SAMPLE_ISSUE         DBConnection.CreateSampleDataAfterEngagementApproval / PKG_SM.P_ADD_SAMPLE_DATA
  9  AUDIT_EXCEPTION_ISSUE      DBConnection.CreateExceptionDataAfterEngagementApproval / PKG_SM.P_ADD_EXCEPTION_DATA
 10  AUDIT_CRITERIA_SUBMITTED   DBConnection.SubmitAuditCriteriaForApproval / PKG_PG.P_SUBMITAUDITCRITERIAFORAPPROVAL (currently dormant)
 11  AJAX_APPLICATION_ERROR     AjaxErrorNotificationMiddleware (application diagnostic)

  Design decisions
  ----------------
  * IAS_NOTIFICATION_MASTER is the runtime master requested here.  It records the
    business caller, related procedure, authoritative data source, templates,
    delivery mechanism and status.  It does not replace workflow tables.
  * Recipient values already returned by an existing business procedure/view are
    passed into the matching notification procedure.  Notification procedures do
    not repeat the business procedure's joins.
  * PARA_STATUS_UPDATED reads V_GET_AIS_POST_COMPLIANCE once.  The workflow should
    call it with vr1.COMID after its existing update; it must remove the duplicate
    ET/AD/MT email joins from P_SUBMITPOSTAUDITCOMPLIANCE_REVIEW.
  * All procedures use one HTML renderer and the existing PKG_INQ.P_ENQUEUE_EMAIL
    queue.  The current IAS queue worker remains the SMTP sender.  No COMMIT is
    issued here, so notification enqueue participates in the caller transaction.
  * FINAL_REPORT_ISSUED queues the HTML message only.  The existing application
    remains responsible for attaching the generated PDF; no attachment workflow is
    changed by this script.
*/

SET DEFINE OFF;

--------------------------------------------------------------------------------
-- 1. Notification master table
--------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'~
    CREATE TABLE IAS_NOTIFICATION_MASTER
    (
      NOTIFICATION_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      NOTIFICATION_CODE     VARCHAR2(100 CHAR) NOT NULL,
      NOTIFICATION_NAME     VARCHAR2(200 CHAR) NOT NULL,
      MODULE_NAME           VARCHAR2(100 CHAR) NOT NULL,
      CALLING_PROCESS       VARCHAR2(300 CHAR) NOT NULL,
      RELATED_PROCEDURE     VARCHAR2(300 CHAR),
      DATA_SOURCE_NAME      VARCHAR2(300 CHAR),
      SUBJECT_TEMPLATE      VARCHAR2(1000 CHAR) NOT NULL,
      TITLE_TEMPLATE        VARCHAR2(500 CHAR) NOT NULL,
      SUMMARY_TEMPLATE      CLOB NOT NULL,
      NOTIFICATION_TYPE     VARCHAR2(30 CHAR) DEFAULT 'TRANSACTIONAL' NOT NULL,
      DELIVERY_MECHANISM    VARCHAR2(100 CHAR) DEFAULT 'PKG_INQ.P_ENQUEUE_EMAIL' NOT NULL,
      CONTENT_TYPE          VARCHAR2(100 CHAR) DEFAULT 'text/html; charset=utf-8' NOT NULL,
      PRIORITY_CODE         VARCHAR2(10 CHAR) DEFAULT 'NORMAL' NOT NULL,
      IS_ACTIVE             CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
      REQUIRES_ATTACHMENT   CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
      DESCRIPTION           VARCHAR2(1000 CHAR),
      CREATED_BY            VARCHAR2(100 CHAR) DEFAULT USER NOT NULL,
      CREATED_ON            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_BY            VARCHAR2(100 CHAR),
      UPDATED_ON            TIMESTAMP,
      CONSTRAINT PK_IAS_NOTIFICATION_MASTER PRIMARY KEY (NOTIFICATION_ID),
      CONSTRAINT UQ_IAS_NOTIFICATION_CODE UNIQUE (NOTIFICATION_CODE),
      CONSTRAINT CK_IAS_NOTIFICATION_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
      CONSTRAINT CK_IAS_NOTIFICATION_ATTACH CHECK (REQUIRES_ATTACHMENT IN ('Y','N')),
      CONSTRAINT CK_IAS_NOTIFICATION_TYPE CHECK
        (NOTIFICATION_TYPE IN ('TRANSACTIONAL','SECURITY','TECHNICAL','WORKFLOW')),
      CONSTRAINT CK_IAS_NOTIFICATION_PRIORITY CHECK
        (PRIORITY_CODE IN ('LOW','NORMAL','HIGH'))
    )~';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE IAS_NOTIFICATION_MASTER IS
  'Central runtime registry for every IAS email notification and its authoritative source/process.';

CREATE OR REPLACE VIEW V_IAS_NOTIFICATION_MASTER AS
SELECT NOTIFICATION_ID, NOTIFICATION_CODE, NOTIFICATION_NAME, MODULE_NAME,
       CALLING_PROCESS, RELATED_PROCEDURE, DATA_SOURCE_NAME, SUBJECT_TEMPLATE,
       TITLE_TEMPLATE, SUMMARY_TEMPLATE, NOTIFICATION_TYPE, DELIVERY_MECHANISM,
       CONTENT_TYPE, PRIORITY_CODE, IS_ACTIVE, REQUIRES_ATTACHMENT, DESCRIPTION
  FROM IAS_NOTIFICATION_MASTER;

/*
  The reviewed V_GET_AIS_POST_COMPLIANCE exposes the compliance/entity business
  data but, in the checked-in package source, does not expose TO_EMAIL/CC_EMAIL.
  This adapter is therefore the single centralized source for that notification.
  If the deployed V_GET_AIS_POST_COMPLIANCE already exposes these addresses,
  replace the three entity joins below with those view columns before deployment.
*/
CREATE OR REPLACE VIEW V_IAS_POST_COMPLIANCE_NOTIFY AS
SELECT C.COM_ID,
       C.PARA_NO,
       C.GIST_OF_PARAS,
       C.ENTITY_ID,
       ET.EMAIL_ADDRESS AS TO_EMAIL,
       RTRIM(AD.EMAIL_ADDRESS||';'||MT.EMAIL_ADDRESS,';') AS CC_EMAIL
  FROM V_GET_AIS_POST_COMPLIANCE C
  JOIN T_AUDITEE_ENTITIES_MAPING M ON M.ENTITY_ID=C.ENTITY_ID
  JOIN T_AUDITEE_ENTITIES ET ON ET.ENTITY_ID=M.ENTITY_ID
  JOIN T_AUDITEE_ENTITIES MT ON MT.ENTITY_ID=M.PARENT_ID
  JOIN T_AUDITEE_ENTITIES AD ON AD.ENTITY_ID=ET.AUDITBY_ID;


-- IAS executive page/API constraint migration for Head Audit Monitoring page 1000401.
-- Run separately BEFORE executive_dashboard_page_api_manifest.sql.
-- DDL commits implicitly in Oracle. DBA must review and back up the constraint first.
-- Approved page IDs: 1000300..1000305 and 1000401. No other IDs allowed.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
SET SERVEROUTPUT ON;

DECLARE
  v_count NUMBER;
  v_condition VARCHAR2(4000);
BEGIN
  SELECT COUNT(*), MAX(SEARCH_CONDITION_VC)
    INTO v_count, v_condition
    FROM ALL_CONSTRAINTS
   WHERE OWNER=SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
     AND TABLE_NAME='T_IAS_EXEC_PAGE_API'
     AND CONSTRAINT_NAME='CK_IAS_EXEC_PAGE_POS'
     AND CONSTRAINT_TYPE='C'
     AND STATUS='ENABLED';
  IF v_count<>1 THEN
    RAISE_APPLICATION_ERROR(-20940,'Expected one enabled CK_IAS_EXEC_PAGE_POS in current schema');
  END IF;

  SELECT COUNT(*) INTO v_count
    FROM T_IAS_EXEC_PAGE_API
   WHERE PAGE_ID NOT BETWEEN 1000300 AND 1000305
     AND PAGE_ID<>1000401;
  IF v_count<>0 THEN
    RAISE_APPLICATION_ERROR(-20941,'Unexpected existing PAGE_ID values; review before constraint migration');
  END IF;

  IF REGEXP_REPLACE(UPPER(v_condition),'[[:space:]()]','')=
       'PAGE_IDBETWEEN1000300AND1000305' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE T_IAS_EXEC_PAGE_API DROP CONSTRAINT CK_IAS_EXEC_PAGE_POS';
    EXECUTE IMMEDIATE 'ALTER TABLE T_IAS_EXEC_PAGE_API ADD CONSTRAINT CK_IAS_EXEC_PAGE_POS CHECK ((PAGE_ID BETWEEN 1000300 AND 1000305) OR PAGE_ID=1000401) ENABLE VALIDATE';
    DBMS_OUTPUT.PUT_LINE('Extended CK_IAS_EXEC_PAGE_POS to allow 1000401.');
  ELSIF REGEXP_REPLACE(UPPER(v_condition),'[[:space:]()]','') IN (
    'PAGE_IDBETWEEN1000300AND1000305ORPAGE_ID=1000401',
    'PAGE_ID=1000401ORPAGE_IDBETWEEN1000300AND1000305'
  ) THEN
    DBMS_OUTPUT.PUT_LINE('Constraint already allows 1000401; no changes.');
  ELSE
    RAISE_APPLICATION_ERROR(-20942,'Constraint definition differs from reviewed baseline; no changes: '||v_condition);
  END IF;
END;
/

SELECT CONSTRAINT_NAME,STATUS,SEARCH_CONDITION_VC
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME='T_IAS_EXEC_PAGE_API'
   AND CONSTRAINT_NAME='CK_IAS_EXEC_PAGE_POS';

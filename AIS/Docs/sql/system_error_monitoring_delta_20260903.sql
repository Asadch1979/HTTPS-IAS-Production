DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM USER_TABLES
   WHERE TABLE_NAME = 'T_AU_SYSTEM_ERROR_STATUS_HISTORY';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE T_AU_SYSTEM_ERROR_STATUS_HISTORY
      (
          STATUS_HISTORY_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          ERROR_ID           NUMBER NOT NULL,
          OLD_STATUS         VARCHAR2(30),
          NEW_STATUS         VARCHAR2(30) NOT NULL,
          CHANGED_BY_PPNO    VARCHAR2(50),
          CHANGED_ON_UTC     TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
          REMARKS            VARCHAR2(1000),
          CONSTRAINT FK_AU_SYS_ERR_STATUS_MASTER
              FOREIGN KEY (ERROR_ID) REFERENCES T_AU_SYSTEM_ERROR_MASTER(ERROR_ID)
      )';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM USER_IND_COLUMNS
   WHERE INDEX_NAME = 'IX_AU_SYS_ERR_STATUS_ERROR_ID';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AU_SYS_ERR_STATUS_ERROR_ID ON T_AU_SYSTEM_ERROR_STATUS_HISTORY (ERROR_ID, CHANGED_ON_UTC)';
  END IF;
END;

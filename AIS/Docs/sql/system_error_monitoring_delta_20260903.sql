DECLARE
  v_admin_menu_id NUMBER;
  v_page_id NUMBER;

  PROCEDURE ensure_page(p_path IN VARCHAR2, p_title IN VARCHAR2) IS
  BEGIN
    BEGIN
      SELECT PAGE_ID
        INTO v_page_id
        FROM T_MENU_PAGES
       WHERE UPPER(PAGE_URL) = UPPER('/' || p_path)
          OR (UPPER(CONTROLLER_NAME) = 'ADMINISTRATIONPANEL'
          AND UPPER(ACTION_NAME) = UPPER(SUBSTR(p_path, INSTR(p_path, '/') + 1)))
       FETCH FIRST 1 ROWS ONLY;

      UPDATE T_MENU_PAGES
         SET CONTROLLER_NAME = 'AdministrationPanel',
             ACTION_NAME = SUBSTR(p_path, INSTR(p_path, '/') + 1),
             PAGE_URL = '/' || p_path,
             PAGE_TITLE = p_title,
             HIDE_MENU = 1
       WHERE PAGE_ID = v_page_id;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        INSERT INTO T_MENU_PAGES
          (MENU_ID, PAGE_TITLE, PAGE_URL, CONTROLLER_NAME, ACTION_NAME, HIDE_MENU, PAGE_KEY)
        VALUES
          (v_admin_menu_id, p_title, '/' || p_path, 'AdministrationPanel',
           SUBSTR(p_path, INSTR(p_path, '/') + 1), 1, UPPER(REPLACE(p_path, '/', '_')))
        RETURNING PAGE_ID INTO v_page_id;
    END;

    MERGE INTO T_MENU_PAGES_GROUPMAP dst
    USING (SELECT v_page_id PAGE_ID, 1 GROUP_ID FROM dual) src
       ON (dst.PAGE_ID = src.PAGE_ID AND dst.GROUP_ID = src.GROUP_ID)
     WHEN NOT MATCHED THEN
       INSERT (PAGE_ID, GROUP_ID) VALUES (src.PAGE_ID, src.GROUP_ID);
  END;
BEGIN
  BEGIN
    SELECT MENU_ID
      INTO v_admin_menu_id
      FROM T_MENUS
     WHERE UPPER(MENU_NAME) IN ('ADMIN', 'ADMINISTRATION')
     FETCH FIRST 1 ROWS ONLY;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      SELECT MIN(MENU_ID) INTO v_admin_menu_id FROM T_MENUS;
  END;

  ensure_page('AdministrationPanel/SystemErrorMonitoring', 'System Error Monitoring');
  ensure_page('AdministrationPanel/SystemErrorDetail', 'System Error Detail');
  ensure_page('AdministrationPanel/GetSystemErrors', 'System Error Data');
  ensure_page('AdministrationPanel/ResolveSystemError', 'Resolve System Error');
  ensure_page('AdministrationPanel/ExportSystemErrors', 'Export System Errors');
END;
/

COMMIT;


DECLARE
  v_constraint_name VARCHAR2(128);
BEGIN
  FOR c IN (
    SELECT acc.CONSTRAINT_NAME
      FROM USER_CONSTRAINTS acc
      JOIN USER_CONS_COLUMNS col
        ON col.CONSTRAINT_NAME = acc.CONSTRAINT_NAME
     WHERE acc.TABLE_NAME = 'T_AU_SYSTEM_ERROR_MASTER'
       AND acc.CONSTRAINT_TYPE = 'C'
       AND col.COLUMN_NAME = 'EMAIL_SENT'
       AND UPPER(acc.SEARCH_CONDITION_VC) LIKE '%EMAIL_SENT%'
       AND UPPER(acc.SEARCH_CONDITION_VC) NOT LIKE '%''P''%'
  ) LOOP
    v_constraint_name := c.CONSTRAINT_NAME;
    EXECUTE IMMEDIATE 'ALTER TABLE T_AU_SYSTEM_ERROR_MASTER DROP CONSTRAINT ' || v_constraint_name;
  END LOOP;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'T_AU_SYSTEM_ERROR_MASTER'
     AND CONSTRAINT_NAME = 'CK_AU_SYS_ERR_EMAIL_SENT';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE T_AU_SYSTEM_ERROR_MASTER ADD CONSTRAINT CK_AU_SYS_ERR_EMAIL_SENT CHECK (EMAIL_SENT IN (''Y'',''N'',''P''))';
  END IF;
END;

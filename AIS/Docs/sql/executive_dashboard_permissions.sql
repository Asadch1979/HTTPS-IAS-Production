-- Review reserved page IDs and verified role IDs before execution by IAS DBA.
-- TOP/GROUP remain disabled until their IAS role IDs have been verified.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
DECLARE
  V_TOP_ROLE NUMBER := NULL;
  V_GROUP_ROLE NUMBER := NULL;
  V_MENU_ID NUMBER;
  V_API_ID NUMBER;
  V_COLLISIONS NUMBER;
  PROCEDURE REGISTER_PAGE(P_ID NUMBER, P_TYPE VARCHAR2, P_ROLE NUMBER) IS
  BEGIN
    SELECT COUNT(*) INTO V_COLLISIONS FROM T_MENU_PAGES
     WHERE ID = P_ID AND NVL(PAGE_KEY, '#') <> 'EXECUTIVE_' || P_TYPE;
    IF V_COLLISIONS > 0 THEN
      RAISE_APPLICATION_ERROR(-20020, 'Executive page ID collision; resolve before deployment.');
    END IF;
    MERGE INTO T_MENU_PAGES P
    USING (SELECT P_ID ID FROM DUAL) S ON (P.ID = S.ID)
    WHEN MATCHED THEN UPDATE SET
      P.PAGE_NAME = 'Executive Dashboard ' || P_TYPE,
      P.PAGE_PATH = 'ExecutiveOverview/' || P_TYPE,
      P.PAGE_URL = '/ExecutiveOverview/' || P_TYPE,
      P.STATUS = 'A', P.HIDE_MENU = 0
    WHEN NOT MATCHED THEN INSERT
      (ID, MENU_ID, PAGE_NAME, PAGE_PATH, PAGE_ORDER, STATUS, HIDE_MENU, PAGE_KEY, PAGE_URL)
    VALUES
      (P_ID, V_MENU_ID, 'Executive Dashboard ' || P_TYPE, 'ExecutiveOverview/' || P_TYPE,
       80 + P_ID - 1000300, 'A', 0, 'EXECUTIVE_' || P_TYPE, '/ExecutiveOverview/' || P_TYPE);
    -- Super User has one actual IAS role and four separately registered menu pages.
    FOR R IN (SELECT 1 ROLE_ID FROM DUAL
              UNION SELECT P_ROLE FROM DUAL WHERE P_ROLE IS NOT NULL) LOOP
      INSERT INTO T_MENU_PAGES_GROUPMAP (GROUPMAP_ID, GROUP_ID, PAGE_ID)
      SELECT (SELECT NVL(MAX(GROUPMAP_ID), 0) + 1 FROM T_MENU_PAGES_GROUPMAP), R.ROLE_ID, P_ID
        FROM DUAL WHERE NOT EXISTS
        (SELECT 1 FROM T_MENU_PAGES_GROUPMAP WHERE GROUP_ID = R.ROLE_ID AND PAGE_ID = P_ID);
    END LOOP;
  END;
  PROCEDURE REGISTER_API(P_ACTION VARCHAR2) IS
  BEGIN
    INSERT INTO T_AU_API_MASTER
      (ACTION_NAME, PAGE_ID, CONTROLLER_NAME, API_PATH, HTTP_METHOD, IS_ACTIVE, CREATED_ON)
    SELECT P_ACTION, 1000300, 'ExecutiveDashboard', '/api/ExecutiveDashboard/' || P_ACTION,
           'GET', 'Y', SYSDATE FROM DUAL WHERE NOT EXISTS
      (SELECT 1 FROM T_AU_API_MASTER WHERE LOWER(API_PATH) = LOWER('/api/ExecutiveDashboard/' || P_ACTION)
       AND UPPER(HTTP_METHOD) = 'GET');
    SELECT API_ID INTO V_API_ID FROM T_AU_API_MASTER
     WHERE LOWER(API_PATH) = LOWER('/api/ExecutiveDashboard/' || P_ACTION) AND UPPER(HTTP_METHOD) = 'GET';
    FOR R IN (SELECT 1 ROLE_ID FROM DUAL UNION SELECT 3 FROM DUAL UNION SELECT 38 FROM DUAL
              UNION SELECT V_TOP_ROLE FROM DUAL WHERE V_TOP_ROLE IS NOT NULL
              UNION SELECT V_GROUP_ROLE FROM DUAL WHERE V_GROUP_ROLE IS NOT NULL) LOOP
      INSERT INTO T_AU_ROLE_API_PERMISSION (ROLE_ID, API_ID, IS_ACTIVE, CREATED_BY)
      SELECT R.ROLE_ID, V_API_ID, 'Y', NULL FROM DUAL WHERE NOT EXISTS
        (SELECT 1 FROM T_AU_ROLE_API_PERMISSION WHERE ROLE_ID = R.ROLE_ID AND API_ID = V_API_ID);
    END LOOP;
  END;
BEGIN
  IF V_TOP_ROLE <= 0 OR V_GROUP_ROLE <= 0 OR V_TOP_ROLE = V_GROUP_ROLE OR
     V_TOP_ROLE IN (1, 3, 38) OR V_GROUP_ROLE IN (1, 3, 38) THEN
    RAISE_APPLICATION_ERROR(-20021, 'Provide distinct verified TOP/GROUP executive role IDs.');
  END IF;
  SELECT MENU_ID INTO V_MENU_ID FROM T_MENU_PAGES
   WHERE LOWER(PAGE_PATH) IN ('dashboard/entity_wise_obs', '/dashboard/entity_wise_obs')
   FETCH FIRST 1 ROW ONLY;
  REGISTER_PAGE(1000300, 'TOP', V_TOP_ROLE);
  REGISTER_PAGE(1000301, 'GROUP', V_GROUP_ROLE);
  REGISTER_PAGE(1000302, 'CCO', 38);
  REGISTER_PAGE(1000303, 'CIA', 3);
  REGISTER_API('GetKpiSummary');
  REGISTER_API('GetRiskSummary');
  REGISTER_API('GetAgingSummary');
  REGISTER_API('GetCycleSummary');
  REGISTER_API('GetSettlementTrend');
  REGISTER_API('GetCriticalItems');
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  RAISE;
END;

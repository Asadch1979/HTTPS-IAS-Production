  V_VALID NUMBER;
  V_ERRORS NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_VALID FROM USER_OBJECTS
   WHERE OBJECT_NAME = 'PKG_HD' AND OBJECT_TYPE IN ('PACKAGE', 'PACKAGE BODY') AND STATUS = 'VALID';

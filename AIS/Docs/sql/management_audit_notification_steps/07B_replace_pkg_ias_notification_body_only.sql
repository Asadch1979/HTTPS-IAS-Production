      FROM V_IAS_POST_COMPLIANCE_NOTIFY C
     WHERE C.COM_ID=P_COM_ID;
    V_ROWS:=ROW_HTML('Para No.',V_REF)||ROW_HTML('Status',P_STATUS)||ROW_HTML('Gist of Para',V_GIST);

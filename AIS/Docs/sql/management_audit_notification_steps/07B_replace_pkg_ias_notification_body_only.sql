  PROCEDURE SEND_PARA_STATUS_UPDATED(P_COM_ID NUMBER,P_STATUS VARCHAR2,O_EMAIL_ID OUT NUMBER) IS
    V_REF VARCHAR2(200); V_GIST VARCHAR2(4000); V_TO VARCHAR2(2000); V_CC VARCHAR2(2000); V_ROWS CLOB;

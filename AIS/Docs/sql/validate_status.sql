SELECT object_name,object_type,status
FROM user_objects
WHERE object_name IN ('PKG_HEAD_AUDIT_MONITOR','PKG_AUDIT_SNAP_SCOPE',
 'PKG_EXEC_DASHBOARD','PKG_EXEC_REPORTS','V_HEAD_AUDIT_ENG_SCOPE',
 'V_HEAD_AUDIT_OFFICE_SCOPE','V_HEAD_AUDIT_ROLE_DEPT','V_EXEC_ENTITY_SCOPE','V_EXEC_PARA_BASE')
ORDER BY object_name,object_type;
